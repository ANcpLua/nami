import { recordOutput } from "./semantics.js";
import type { DecoratorContext, Model, Program, Union } from "@typespec/compiler";
import { emitFile, getDiscriminatedUnion } from "@typespec/compiler";
import { resolve } from "node:path";
import { stateKeys } from "./lib.js";
import { mapType, mixedUnionShape } from "./type-map.js";
export function $attributeProjection(context: DecoratorContext, source: Union, target: Union): void {
  context.program.stateMap(stateKeys.attributeProjection).set(source,target);
}
export async function emitAttributeProjection(program: Program): Promise<void> {
  for (const [sourceType,targetType] of program.stateMap(stateKeys.attributeProjection)) {
    const source=sourceType as Union, target=targetType as Union;
    const targetShape=mixedUnionShape(program,target);
    if (targetShape?.objectMember?.type.kind!=="Union") throw new Error("The API attribute representation needs a tagged object union");
    const [tagged]=getDiscriminatedUnion(program,targetShape.objectMember.type);
    if(!tagged) throw new Error("Attribute objects require explicit tags");
    const sourceObject=[...source.variants.values()].map(v=>v.type).find(t=>t.kind==="Model" && !t.indexer) as Model | undefined;
    if(!sourceObject) throw new Error("Stored attributes require a tagged object model");
    const sourceName=mapType(program,source).replace(/\?$/u,"");
    const targetName=mapType(program,target).replace(/\?$/u,"");
    const objectArms:string[]=[];
    for(const [tag,model] of tagged.variants) {
      if (model.kind !== "Model") throw new Error(`Attribute case ${tag} must be a model`);
      const property=[...model.properties.values()].find(p=>p.name!=="kind");
      if(!property) throw new Error(`No value property on ${model.name}`);
      const sourceModel=sourceObject.derivedModels.flatMap(m=>m.derivedModels.length?m.derivedModels:[m]).find(m=>m.properties.get("type")?.type.kind==="String" && (m.properties.get("type")!.type as {value:string}).value===tag);
      if(!sourceModel) throw new Error(`No stored representation for attribute tag ${tag}`);
      const name=property.name[0]!.toUpperCase()+property.name.slice(1);
      const value=tag==="kvlist" ? `item.${name}.ToDictionary(pair => pair.Key, pair => ToContract(pair.Value), StringComparer.Ordinal)` : `item.${name}`;
      objectArms.push(`        ${mapType(program,sourceModel)} item => new ${targetName}.ObjectValue(new ${mapType(program,model)} { ${name} = ${value} }),`);
    }
    const text=`// <auto-generated/>\n#nullable enable\nusing System;\nusing System.Linq;\nnamespace Nami.Collector.Storage;\ninternal static class StoredAttributeProjection\n{\n    internal static ${targetName}? ToContract(${sourceName}? value) => value switch\n    {\n        null => null,\n        ${sourceName}.StringValue item => new ${targetName}.StringValue(item.Value),\n        ${sourceName}.BoolValue item => new ${targetName}.BoolValue(item.Value),\n        ${sourceName}.ArrayValue item => new ${targetName}.ArrayValue(item.Items.Select(ToContract).ToArray()),\n        ${sourceName}.ObjectValue item => ObjectToContract(item.Value),\n    };\n    private static ${targetName} ObjectToContract(${mapType(program,sourceObject)} value) => value switch\n    {\n${objectArms.join("\n")}\n        null => throw new ArgumentNullException(nameof(value))\n    };\n}\n`;
    await emitFile(program,{path:recordOutput(program,resolve(program.projectRoot,"../src/nami.collector.storage/Generated/StoredAttributeProjection.g.cs")),content:text});
  }
}

export function $storageAttributeProjection(context: DecoratorContext, source: Union, target: Union): void {
  context.program.stateMap(stateKeys.attributeIngestionProjection).set(source,target);
}
export async function emitStorageAttributeProjection(program: Program): Promise<void> {
  for (const [sourceType,targetType] of program.stateMap(stateKeys.attributeIngestionProjection)) {
    const source=sourceType as Union, target=targetType as Union;
    const sourceName=mapType(program,source).replace(/\?$/u, "");
    const targetName=mapType(program,target).replace(/\?$/u, "");
    const object=[...target.variants.values()].map(v=>v.type).find(t=>t.kind==="Model" && !t.indexer) as Model | undefined;
    if(!object) throw new Error("A stored value needs tagged object alternatives");
    const leaves=(model: Model): Model[] => model.derivedModels.length ? model.derivedModels.flatMap(leaves) : [model];
    const tagged=new Map(leaves(object).map(model=> {
      const tag=model.properties.get("type")?.type;
      if(tag?.kind!=="String") throw new Error(`Missing stored tag on ${model.name}`);
      return [tag.value,model];
    }));
    const wrap=(tag: string,value: string): string => {
      const model=tagged.get(tag);
      if(!model) throw new Error(`Missing stored ${tag} alternative`);
      const property=[...model.properties.values()].find(p=>p.name!=="type")!;
      const name=property.name[0]!.toUpperCase()+property.name.slice(1);
      return `new ${targetName}.ObjectValue(new ${mapType(program,model)} { ${name} = ${value} })`;
    };
    const arms=[...source.variants].map(([key,variant])=> {
      const type=variant.type, cs=mapType(program,type), getter=`value.As${cs==="long" ? "Int64" : String(key)}()`;
      let expression: string;
      if(type.kind==="Intrinsic" && type.name==="null") expression="null";
      else if(type.kind==="Model" && type.indexer?.key.name==="integer") expression=`new ${targetName}.ArrayValue(${getter}!.Select(ToStored).ToArray())`;
      else if(type.kind==="Model" && type.indexer) expression=wrap("kvlist",`CanonicalAttributeOrder.Apply(${getter}!).ToDictionary(item => item.Key, item => ToStored(item.Value), StringComparer.Ordinal)`);
      else if(cs==="string") expression=`new ${targetName}.StringValue(${getter}!)`;
      else if(cs==="bool") expression=`new ${targetName}.BoolValue(${getter}!.Value)`;
      else if(cs==="long") expression=wrap("int",`${getter}!.Value`);
      else if(cs==="double") expression=wrap("double",`${getter}!.Value`);
      else if(type.kind==="Scalar" && type.name==="bytes") expression=wrap("bytes",`${getter}!`);
      else throw new Error(`No stored representation for ${String(key)}`);
      return `        ${sourceName}Kind.${String(key)} => ${expression},`;
    });
    await emitFile(program,{path:recordOutput(program,resolve(program.projectRoot,"../src/nami.collector.storage/Generated/AttributeIngestion.g.cs")),content:`// <auto-generated/>\n#nullable enable\nusing System;\nusing System.Linq;\nnamespace Nami.Collector.Storage;\ninternal static class StoredRecordMapper\n{\n    internal static ${targetName}? ToStored(${sourceName} value) => value.Kind switch\n    {\n${arms.join("\n")}\n        _ => throw new InvalidOperationException("Unknown ingestion value kind.")\n    };\n}\n`});
  }
}
