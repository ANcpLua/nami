const HEADER = "﻿// <auto-generated/>\n// Copyright (c) 2025-2026 ancplua\n#nullable enable\n\nusing System.Linq;\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\n";

type Bucket = {
  namespace: string;
  scalars: Scalar[];
  models: Array<[Model, string]>;
  enums: Enum[];
  unions: Union[];
  mediaTypes: Map<string, string>;
};

export async function $onEmit(context: EmitContext): Promise<void> {
  const program = context.program;
  if (program.compilerOptions.noEmit) return;

  const buckets = new Map<string, Bucket>();
  const emittedNames = new Set<Type>();
  const candidates: {type: Type; scope: string; name: string}[] = [];
  navigateProgram(program, { model(model) {
    if (model.name && !isInTypeSpec(model) && !outputFor(program, model)) candidates.push({type:model, scope:resolveNamespace(program,model) ?? "", name:instantiationName(program,model)});
  } });
  allocateNames(program, candidates);

  navigateProgram(program, {
    model: (m) => {
      if (isInTypeSpec(m) || outputFor(program, m)) return;
      if (!m.name) return;
      const ns = resolveNamespace(program, m);
      if (!ns) return;
      collectMediaType(program, m, getBucket(buckets, ns));
      const hasBodyProperty = inheritedProperties(m)
        .some((property) => !isHttpMetadata(program, property));
      const isExplicitEmptyModel = m.properties.size === 0 && !m.baseModel;
      if (!hasBodyProperty && !isExplicitEmptyModel) return;
      // Template instantiations share the base name (`CursorPage`); use the instantiated
      // form `CursorPageTrace` so each instantiation produces a distinct type. Template
      // DEFINITIONS are not navigated, so this only fires on concrete instantiations.
      const emittedName = instantiationName(program, m);
      if (emittedNames.has(m)) return;
      emittedNames.add(m);
      getBucket(buckets, ns).models.push([m, emittedName]);
    },
    enum: (e) => {
      if (isInTypeSpec(e) || outputFor(program, e)) return;
      const ns = resolveNamespace(program, e);
      if (!ns) return;
      getBucket(buckets, ns).enums.push(e);
    },
    union: (u) => {
      if (isInTypeSpec(u) || outputFor(program, u) || !u.name) return;
      if (!hasCsharpPolymorphic(program, u) && !isDiscriminatedUnion(program, u) && !mixedUnionShape(program, u)) return;
      const ns = resolveNamespace(program, u);
      if (!ns) return;
      getBucket(buckets, ns).unions.push(u);
    },
    scalar: (s) => {
      if (isInTypeSpec(s) || outputFor(program, s) || !s.name || !hasCsharpBrand(program, s)) return;
      const ns = resolveNamespace(program, s);
      if (!ns) return;
      getBucket(buckets, ns).scalars.push(s);
    },
  });

  const unions = [...buckets.values()].flatMap((bucket) => bucket.unions);
  const routes = routeParameters(program);
  for (const [ns, bucket] of buckets) {
    const path = `${context.emitterOutputDir}/${ns.replace(/\./g, "/")}.cs`;
    const content = renderBucket(program, bucket, unions);
    await emitFile(program, { path, content: ns === routes.namespace ? `${content}\n${routes.content}` : content });
  }
  const entries: Array<[string, string]> = [];
  for (const bucket of buckets.values()) {
    const internalBases = polymorphicBaseModels(bucket.unions);
    for (const [model, name] of bucket.models) {
      if (internalBases.has(model)) continue;
      entries.push([`${bucket.namespace}.${name}`, getFriendlyName(program, model) ?? `${getNamespaceFullName(model.namespace!)}.${name}`.replace(/^Nami\.Api\.Contracts\./u, "")]);
    }
    for (const union of bucket.unions) entries.push([`${bucket.namespace}.${union.name}`, `${getNamespaceFullName(union.namespace!)}.${union.name}`.replace(/^Nami\.Api\.Contracts\./u, "")]);
    for (const enm of bucket.enums) entries.push([`${bucket.namespace}.${enm.name}`, `${getNamespaceFullName(enm.namespace!)}.${enm.name}`.replace(/^Nami\.Api\.Contracts\./u, "")]);
  }
  entries.sort((a, b) => a[1].localeCompare(b[1]));
  const analysis = entries.filter(([, name]) => /^Tools\.\w+Input$/.test(name) && entries.some(([, output]) => output === name.replace(/Input$/, "Result")));
  const analysisCases = analysis.map(([, name]) => {
    const operation = name.slice("Tools.".length, -"Input".length).replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
    return `        "${operation}" => ("${name}", "${name.replace(/Input$/, "Result")}"),`;
  }).join("\n");
  const [httpServices] = getAllHttpServices(program);
  const arrayBodies = new Set(httpServices.flatMap(service => service.operations).flatMap(operation => operation.responses)
    .flatMap(response => response.responses).map(response => response.body)
    .filter(body => body?.bodyKind === "single" && body.type.kind === "Model" && isArrayModelType(body.type))
    .map(body => `${mapType(program, (body!.type as Model).indexer!.value)}[]`));
  await emitOutputs(program);
  await emitProjections(program);
  await emitModelProjections(program);
  await emitCatalogProjections(program);
  await emitAttributeProjection(program);
  await emitStorageAttributeProjection(program);
  await emitToolMetadata(program, context.emitterOutputDir);
  await emitExactSchema(program);
  await emitFile(program,{path:`${program.projectRoot}/generated/consumer-files.json`, content:JSON.stringify(outputFiles(program).map(path=>relative(resolve(program.projectRoot,".."),path).replaceAll("\\", "/")).sort(),null,2)+"\n"});
  const generated = `// <auto-generated/>\n#nullable enable\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\nusing System.Text.Json.Serialization.Metadata;\nnamespace Nami.Api.Contracts;\n\npublic static class ContractTypes\n{\n    public static IJsonTypeInfoResolver Resolver => GeneratedContractJsonContext.Default;\n    public static IReadOnlyList<string> Tools { get; } = [${analysis.map(([, name]) => JSON.stringify(name.slice("Tools.".length, -"Input".length).replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase())).join(", ")}];\n    public static JsonTypeInfo<T> TypeInfo<T>() => GeneratedContractJsonContext.Default.Options.GetTypeInfo<T>();\n    public static (string Input, string Output) Analysis(string operation) => operation switch\n    {\n${analysisCases}\n        _ => throw new ArgumentException($"No generated analysis contract for {operation}.", nameof(operation))\n    };\n    public static string NameOf(Type type) => type switch\n    {\n${entries.map(([type, name]) => `        _ when type == typeof(global::${type}) => ${JSON.stringify(name)},`).join("\n")}\n        _ => throw new ArgumentException($"No generated contract for {type}.", nameof(type))\n    };\n    public static JsonTypeInfo TypeInfo(string name) => name switch\n    {\n${entries.map(([type, name]) => {
    return `        ${JSON.stringify(name)} => GeneratedContractJsonContext.Default.GetTypeInfo(typeof(global::${type}))!,`;
  }).join("\n")}\n        _ => throw new ArgumentException($"No generated serializer for {name}.", nameof(name))\n    };\n}\n\n[JsonSourceGenerationOptions(AllowOutOfOrderMetadataProperties = true, UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow)]\n[JsonSerializable(typeof(JsonElement))]\n${entries.map(([type]) => `[JsonSerializable(typeof(global::${type}))]`).join("\n")}\n${[...arrayBodies].map(type => `[JsonSerializable(typeof(global::${type}))]`).join("\n")}\ninternal partial class GeneratedContractJsonContext : JsonSerializerContext;\n`;
  await emitFile(program, { path: `${context.emitterOutputDir}/Nami/Api/Contracts/ContractTypes.cs`, content: generated });
}

/**
 * Every path and query parameter of the service's HTTP operations that the contract bounds by a length or a pattern,
 * by its operation's method and route, rendered in the service's namespace, so a server refuses a parameter outside
 * them from the contract, as it refuses a body member, whichever route takes it.
 */
function routeParameters(program: Program): { namespace: string | undefined; content: string } {
  const [services] = getAllHttpServices(program);
  const entries: string[] = [];
  const numbers: string[] = [];
  for (const operation of services.flatMap((service) => service.operations)) {
    for (const parameter of operation.parameters.parameters) {
      if (parameter.type !== "path" && parameter.type !== "query") continue;
      const property = parameter.param;
      const range = numericRange(program, property, mapType(program, property.type));
      if (range !== undefined) {
        const fallback = property.defaultValue?.valueKind === "NumericValue" ? property.defaultValue.value.toString() : "null";
        numbers.push(`        ("${operation.verb.toUpperCase()}", "${escapeCsharpString(operation.path)}", "${escapeCsharpString(parameter.name)}", new(${fallback}, ${range.minimum ?? "null"}, ${range.maximum ?? "null"})),`);
      }
      if (property.type.kind !== "Scalar" || !isStringScalar(property.type)) continue;
      const minimum = numericBound(program, property, getMinLength, true);
      const maximum = numericBound(program, property, getMaxLength, true);
      const pattern = getPattern(program, property) ?? scalarPattern(program, property.type);
      if (minimum === undefined && maximum === undefined && pattern === undefined) continue;
      entries.push(`        ("${operation.verb.toUpperCase()}", "${escapeCsharpString(operation.path)}", "${escapeCsharpString(parameter.name)}", "${parameter.type}", ${minimum ?? "null"}, ${maximum ?? "null"}, ${pattern === undefined ? "null" : `"${escapeCsharpString(pattern)}"`}),`);
    }
  }
  const service = services.find(() => true)?.namespace;
  return {
    namespace: service === undefined ? undefined : getCsharpNamespace(program, service),
    content: "/// <summary>\n/// Each path and query parameter of an HTTP operation the contract bounds, by the operation's method and route: where it\n"
      + "/// travels, the characters it keeps, counted as code points, and the ECMAScript pattern it matches, as JSON Schema's\n"
      + "/// pattern reads it.\n/// </summary>\n"
      + "public static class RouteParameters\n{\n"
      + "    public static readonly IReadOnlyList<(string Method, string Route, string Name, string In, int? MinLength, int? MaxLength, string? Pattern)> All =\n"
      + `    [${entries.length === 0 ? "" : `\n${entries.join("\n")}\n    `}];\n`
      + "    public readonly record struct NumericParameter(double? Default, double? Minimum, double? Maximum);\n"
      + "    private static readonly (string Method, string Route, string Name, NumericParameter Value)[] Numbers =\n"
      + `    [${numbers.length === 0 ? "" : `\n${numbers.join("\n")}\n    `}];\n`
      + "    public static NumericParameter Number(string method, string route, string name) => Numbers.Single(item => item.Method == method && item.Route == route && item.Name == name).Value;\n}\n",
  };
}

function instantiationName(program: Program, model: Model): string {
  const allocated = languageName(program, model, "");
  if (allocated) return allocated;
  if (!model.templateMapper?.args.length) return model.name;
  const parts = [model.name];
  for (const arg of model.templateMapper.args) {
    if ("kind" in arg && "name" in arg && typeof arg.name === "string") {
      parts.push(pascal(arg.name));
    }
  }
  return parts.join("");
}

function isInTypeSpec(type: { namespace?: { name?: string; namespace?: unknown } }): boolean {
  let cursor: { name?: string; namespace?: unknown } | undefined = type.namespace;
  while (cursor) {
    if (cursor.name === "TypeSpec") return true;
    cursor = cursor.namespace as typeof cursor;
  }
  return false;
}

function getBucket(buckets: Map<string, Bucket>, namespace: string): Bucket {
  let b = buckets.get(namespace);
  if (!b) {
    b = { namespace, scalars: [], models: [], enums: [], unions: [], mediaTypes: new Map() };
    buckets.set(namespace, b);
  }
  return b;
}

function resolveNamespace(program: Program, type: Model | Enum | Scalar | Union): string | undefined {
  const own = getCsharpNamespace(program, type);
  if (own) return own;
  let cursor = type.namespace;
  while (cursor) {
    const mapped = getCsharpNamespace(program, cursor);
    if (mapped) return mapped;
    cursor = cursor.namespace;
  }
  return undefined;
}

function renderBucket(program: Program, bucket: Bucket, unions: Union[]): string {
  const out: string[] = [HEADER];
  out.push(`namespace ${bucket.namespace};\n`);
  for (const scalar of bucket.scalars) out.push(renderBrandedScalar(scalar));
  for (const [name, value] of bucket.mediaTypes) out.push(renderMediaType(name, value));
  for (const union of bucket.unions) {
    const mixed = mixedUnionShape(program, union);
    out.push(mixed ? renderMixedUnion(program, union, mixed) : renderPolymorphicUnion(program, union));
  }
  const internalBases = polymorphicBaseModels(bucket.unions);
  for (const [m, name] of bucket.models) {
    if (!internalBases.has(m)) out.push(renderModel(program, m, name, unions));
  }
  for (const e of bucket.enums) out.push(renderEnum(program, e));
  return out.join("\n");
}

function renderBrandedScalar(scalar: Scalar): string {
  if (!isStringScalar(scalar)) {
    throw new Error(`@csharpBrand scalar '${scalar.name}' must extend string.`);
  }
  const name = scalar.name;
  const converter = `${name}JsonConverter`;
  return `[JsonConverter(typeof(${converter}))]\npublic readonly record struct ${name}(string Value)\n{\n    public override string ToString() => Value;\n}\n\npublic sealed class ${converter} : JsonConverter<${name}>\n{\n    public override ${name} Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)\n    {\n        if (reader.TokenType != JsonTokenType.String) throw new JsonException("${name} must be a JSON string.");\n        return new ${name}(reader.GetString() ?? throw new JsonException("${name} cannot be null."));\n    }\n\n    public override void Write(Utf8JsonWriter writer, ${name} value, JsonSerializerOptions options) =>\n        writer.WriteStringValue(value.Value);\n}\n`;
}

function isStringScalar(scalar: Scalar): boolean {
  if (scalar.name === "string") return true;
  return scalar.baseScalar ? isStringScalar(scalar.baseScalar) : false;
}

function polymorphicBaseModels(unions: Union[]): Set<Model> {
  const result = new Set<Model>();
  for (const union of unions) {
    for (const variant of union.variants.values()) {
      if (variant.type.kind === "Model" && variant.type.baseModel) result.add(variant.type.baseModel);
    }
  }
  return result;
}

/**
 * A model that declares its own `@mediaTypeHint` (ProblemDetails) gets a constant for it, so a
 * server writes the published media type instead of a string typed beside it. Derived models
 * inherit the hint and do not repeat the constant.
 */
function collectMediaType(program: Program, model: Model, bucket: Bucket): void {
  const hint = getMediaTypeHint(program, model);
  if (hint === undefined) return;
  if (model.baseModel && getMediaTypeHint(program, model.baseModel) === hint) return;
  bucket.mediaTypes.set(`${model.name}MediaType`, hint);
}

function renderMediaType(name: string, value: string): string {
  return `public static class ${name}\n{\n    public const string Value = "${escapeCsharpString(value)}";\n}\n`;
}

/** The wire discriminator of a tagged union and the tag each variant model carries. */
function taggedUnionInfo(program: Program, union: Union): { property: string; tagOf: (model: Model) => string } | undefined {
  const [discriminated] = getDiscriminatedUnion(program, union);
  if (discriminated) {
    if (discriminated.options.envelope !== "none") {
      throw new Error(`@discriminated union '${union.name}' must use envelope "none"; the emitter has no envelope form.`);
    }
    const tags = new Map<Type, string>();
    for (const [name, type] of discriminated.variants) tags.set(type, name);
    return {
      property: discriminated.options.discriminatorPropertyName,
      tagOf: (model) => {
        const tag = tags.get(model);
        if (tag === undefined) throw new Error(`Model '${model.name}' is not a variant of '${union.name}'.`);
        return tag;
      },
    };
  }
  const property = getCsharpPolymorphicDiscriminator(program, union);
  if (!property) return undefined;
  return {
    property,
    tagOf: (model) => {
      const literal = inheritedProperties(model).find((candidate) =>
        resolveEncodedName(program, candidate, "application/json") === property,
      );
      if (!literal || literal.type.kind !== "String") {
        throw new Error(
          `@csharpPolymorphic union '${union.name}' variant '${model.name}' must have literal string '${property}'.`,
        );
      }
      return literal.type.value;
    },
  };
}

function renderModel(program: Program, model: Model, emittedName: string, unions: Union[]): string {
  const keyword = "public sealed class";
  const memberships = unions.filter((candidate) =>
    !mixedUnionShape(program, candidate) &&
    [...candidate.variants.values()].some((variant) => variant.type === model),
  );
  const implementsUnion = "";
  const discriminators = new Set(memberships.map((union) => taggedUnionInfo(program, union)?.property));
  const constants: string[] = [];
  const props: string[] = [];
  for (const prop of inheritedProperties(model)) {
    if (isHttpMetadata(program, prop)) continue;
    const semantics = resolveProperty(program, prop);
    const jsonName = escapeCsharpString(semantics.jsonName);
    if (discriminators.has(jsonName)) {
      const membership = memberships.find((union) => taggedUnionInfo(program, union)?.property === jsonName)!;
      const tag = taggedUnionInfo(program, membership)!.tagOf(model);
      props.push(`    [JsonPropertyName("${jsonName}")]\n    public string ${pascal(prop.name)} => "${escapeCsharpString(tag)}";`);
      continue;
    }
    const type = mapType(program, prop.type);
    const name = pascal(prop.name);
    constants.push(...renderConstants(program, prop, type.replace(/\?$/, ""), name));
    const numberHandling = renderNumberHandling(program, prop);
    if (prop.optional && type.endsWith("?")) {
      const inner = type.slice(0, -1);
      const converter = numberHandling.match(/JsonConverter\(typeof\((.+)\)\)/u)?.[1] ?? (inner === "double" && hasNamedFloatingPointValues(prop.type) ? "global::Nami.Api.Contracts.NamedDoubleConverter" : undefined);
      const valueConverter = converter && ["long", "ulong", "int", "uint", "short", "ushort", "byte", "sbyte"].includes(inner)
        ? `global::Nami.Api.Contracts.OptionalNullableValueConverter<${inner}, ${converter}>`
        : converter ? `global::Nami.Api.Contracts.OptionalConvertedValueConverter<${type}, ${converter}>`
        : `global::Nami.Api.Contracts.OptionalValueConverter<${type}>`;
      props.push(`    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]\n    [JsonConverter(typeof(${valueConverter}))]\n    [JsonPropertyName("${jsonName}")]\n    public global::Nami.Api.Contracts.OptionalValue<${type}> ${name} { get; init; }`);
    } else if (prop.optional) {
      const optionalType = `${type}?`;
      const ignoreNull = "    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]\n";
      props.push(`${numberHandling}${ignoreNull}    [JsonPropertyName("${jsonName}")]\n    public ${optionalType} ${name} { get; init; }`);
    } else {
      // A required property whose type admits null must be written even when null; a consumer's
      // context-wide WhenWritingNull policy would otherwise drop it and fail its own reader.
      const alwaysWrite = type.endsWith("?") ? "    [JsonIgnore(Condition = JsonIgnoreCondition.Never)]\n" : "";
      props.push(`${numberHandling}${alwaysWrite}    [JsonPropertyName("${jsonName}")]\n    public required ${type} ${name} { get; init; }`);
    }
  }
  const members = [...constants, ...props];
  const body = members.length ? `\n${members.join("\n")}\n` : "\n";
  return `${keyword} ${emittedName}${implementsUnion}\n{${body}}\n`;
}

const NUMERIC_CS_TYPES = new Set(["sbyte", "byte", "short", "ushort", "int", "uint", "long", "ulong", "float", "double", "decimal"]);

/**
 * A property's declared default and its declared numeric range become constants beside it, so a
 * consumer applies the contract's defaults and bounds from these generated values instead of
 * restating them. Numeric bounds use the property's effective constraints, including its scalar.
 */
function renderConstants(program: Program, property: ModelProperty, type: string, name: string): string[] {
  const lines: string[] = [];
  const fallback = defaultLiteral(property, type);
  if (fallback !== undefined) lines.push(`    public const ${type} ${name}Default = ${fallback};`);
  const range = numericRange(program, property, type);
  if (range?.minimum !== undefined) lines.push(`    public const ${type} ${name}Minimum = ${numericLiteral(String(range.minimum), type)};`);
  if (range?.maximum !== undefined) lines.push(`    public const ${type} ${name}Maximum = ${numericLiteral(String(range.maximum), type)};`);
  return lines;
}

/** Effective numeric bounds, including scalar constraints; undefined when neither bound is declared. */
function numericRange(program: Program, property: ModelProperty, type: string): { minimum?: string; maximum?: string } | undefined {
  if (!NUMERIC_CS_TYPES.has(type)) return undefined;
  const minimum = preciseBound(program, property, getMinValueAsNumeric);
  const maximum = preciseBound(program, property, getMaxValueAsNumeric);
  return minimum === undefined && maximum === undefined ? undefined : { minimum, maximum };
}

/**
 * A request body's bounded strings and arrays in one list, so a server rejects a sent value of another length from
 * the contract, whichever operation takes the body.
 */
function scalarPattern(program: Program, scalar: Scalar): string | undefined {
  for (let current: Scalar | undefined = scalar; current; current = current.baseScalar) {
    const pattern = getPattern(program, current);
    if (pattern !== undefined) return pattern;
  }
  return undefined;
}

/**
 * A request body's patterned strings in one list, so a server refuses a sent value that does not match from the contract,
 * whichever operation takes the body.
 */
function defaultLiteral(property: ModelProperty, type: string): string | undefined {
  const value = property.defaultValue;
  switch (value?.valueKind) {
    case "NumericValue":
      return NUMERIC_CS_TYPES.has(type) ? numericLiteral(value.value.toString(), type) : undefined;
    case "StringValue":
      return type === "string" ? `"${escapeCsharpString(value.value)}"` : undefined;
    case "BooleanValue":
      return type === "bool" ? String(value.value) : undefined;
    case "EnumValue":
      return `${type}.${pascal(value.value.name)}`;
    default:
      return undefined;
  }
}

function numericBound(
  program: Program,
  property: ModelProperty,
  read: (program: Program, target: Type) => number | undefined,
  includeScalar: boolean,
): number | undefined {
  const own = read(program, property);
  if (own !== undefined || !includeScalar) return own;
  for (let scalar = property.type.kind === "Scalar" ? property.type as Scalar : undefined; scalar; scalar = scalar.baseScalar) {
    const bound = read(program, scalar);
    if (bound !== undefined) return bound;
  }
  return undefined;
}

function numericLiteral(text: string, type: string): string {
  return type === "float" ? `${text}f` : type === "decimal" ? `${text}m` : text;
}

function encodedValueConverter(program: Program, type: Type): string | undefined {
  if (isNamedFloatingPointUnion(type)) return "global::Nami.Api.Contracts.NamedDoubleConverter";
  const inner = nonNullType(type);
  if (inner !== type) {
    const converter = encodedValueConverter(program, inner);
    if (!converter) return undefined;
    const cs = mapType(program, inner);
    const wrapper = ["long", "ulong", "int", "uint", "short", "ushort", "byte", "sbyte", "double", "float", "decimal", "bool"].includes(cs)
      ? "NullableEncodedValueConverter" : "NullableEncodedReferenceConverter";
    return `global::Nami.Api.Contracts.${wrapper}<${cs}, ${converter}>`;
  }
  if (type.kind === "Scalar") {
    if (effectiveEncoding(program,type)?.type.name !== "string") return undefined;
    const cs = mapType(program,type);
    return cs === "long" ? "global::Nami.Api.Contracts.Int64StringConverter"
      : cs === "ulong" ? "global::Nami.Api.Contracts.UInt64StringConverter" : undefined;
  }
  if (type.kind === "Model" && type.indexer && (isArrayModelType(type) || isRecordModelType(type))) {
    const child = encodedValueConverter(program,type.indexer.value);
    if (!child) return undefined;
    return `global::Nami.Api.Contracts.${isArrayModelType(type) ? "EncodedListConverter" : "EncodedMapConverter"}<${mapType(program,type.indexer.value)}, ${child}>`;
  }
  return undefined;
}

function renderNumberHandling(program: Program, property: ModelProperty): string {
  const type = nonNullType(property.type);
  const composite = type.kind === "Model" && !!type.indexer &&
    (isRecordModelType(type) || (isArrayModelType(type) && (admitsNull(property.type) || type.indexer.value.kind === "Model" || (type.indexer.value.kind === "Union" && !isNamedFloatingPointUnion(type.indexer.value)))));
  const codec = composite ? encodedValueConverter(program,property.type) : undefined;
  if (codec) return `    [JsonConverter(typeof(${codec}))]\n`;
  if (isStringEncodedNumber(program, property)) {
    const type = mapType(program, property.type).replace(/\?$/u, "");
    if (type === "long" || type === "ulong") return `    [JsonConverter(typeof(global::Nami.Api.Contracts.${type === "long" ? "Int64" : "UInt64"}StringConverter))]\n`;
    if (type === "IReadOnlyList<ulong>" || type === "IReadOnlyList<long>") return `    [JsonConverter(typeof(global::Nami.Api.Contracts.IntegerStringListConverter<${type === "IReadOnlyList<ulong>" ? "ulong" : "long"}>))]\n`;
    throw new Error(`String encoding needs a converter for ${type}.`);
  }
  if (hasNamedFloatingPointValues(property.type)) {
    return "    [JsonNumberHandling(JsonNumberHandling.AllowNamedFloatingPointLiterals)]\n";
  }
  const numericType = mapType(program, property.type).replace(/\?$/u, "");
  if (["sbyte", "byte", "short", "ushort", "int", "uint", "long", "ulong"].includes(numericType)) {
    return `    [JsonConverter(typeof(global::Nami.Api.Contracts.ExactIntegerConverter<${numericType}>))]\n`;
  }
  return "";
}

function hasNamedFloatingPointValues(type: Type): boolean {
  if (isNamedFloatingPointUnion(type)) return true;
  if (type.kind === "Model" && isArrayModelType(type)) return hasNamedFloatingPointValues(type.indexer!.value);
  if (type.kind === "Union") {
    const nonNull = [...type.variants.values()].map((variant) => variant.type)
      .filter((member) => member.kind !== "Intrinsic" || member.name !== "null");
    return nonNull.length === 1 && hasNamedFloatingPointValues(nonNull[0]!);
  }
  return false;
}

function isStringEncodedNumber(program: Program, property: ModelProperty): boolean {
  return resolveProperty(program, property).encoding?.type.name === "string";
}

function renderPolymorphicUnion(program: Program, union: Union): string {
  const variants = [...union.variants.values()].map((variant) => {
    if (variant.type.kind !== "Model") throw new Error(`Union ${union.name} contains a non-model case.`);
    return variant.type;
  });
  const name = union.name;
  const converter = `${name}JsonConverter`;
  const tagged = taggedUnionInfo(program, union);
  const caseType = (model: Model) => localOrQualifiedType(program, union, model);
  const reads = variants.map(model => {
    const selector = tagged
      ? `tag == "${escapeCsharpString(tagged.tagOf(model))}"`
      : `root.TryGetProperty("${escapeCsharpString(resolveEncodedName(program, [...model.properties.values()].find(p => !p.optional)! , "application/json"))}", out _)`;
    return `        if (${selector}) return root.Deserialize(options.GetTypeInfo<${caseType(model)}>()) ?? throw new JsonException("Missing ${caseType(model)} case.");`;
  }).join("\n");
  const tagRead = tagged
    ? `        if (!root.TryGetProperty("${escapeCsharpString(tagged.property)}", out var tagProperty) || tagProperty.ValueKind != JsonValueKind.String) throw new JsonException("${name} requires ${escapeCsharpString(tagged.property)}.");\n        var tag = tagProperty.GetString();\n`
    : "";
  const writes = variants.map(model => `            ${caseType(model)} => options.GetTypeInfo<${caseType(model)}>(),`).join("\n");
  return `[JsonConverter(typeof(${converter}))]\npublic readonly union ${name}(${variants.map(caseType).join(", ")});\n\npublic sealed class ${converter} : JsonConverter<${name}>\n{\n    public override ${name} Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)\n    {\n        using var document = JsonDocument.ParseValue(ref reader);\n        var root = document.RootElement;\n        if (root.ValueKind != JsonValueKind.Object) throw new JsonException("${name} must be a JSON object.");\n${tagRead}${reads}\n        throw new JsonException("Unknown ${name} case.");\n    }\n\n    public override void Write(Utf8JsonWriter writer, ${name} value, JsonSerializerOptions options)\n    {\n        System.Text.Json.Serialization.Metadata.JsonTypeInfo typeInfo = value switch\n        {\n${writes}\n            null => throw new InvalidOperationException("An empty ${name} cannot be serialized.")\n        };\n        JsonSerializer.Serialize(writer, value.Value, typeInfo);\n    }\n}\n`;

}

function localOrQualifiedType(program: Program, owner: Model | Union, type: Model | Union): string {
  if (!type.name) throw new Error("A polymorphic model or union must have an emitted name.");
  return resolveNamespace(program, owner) === resolveNamespace(program, type) ? type.name : mapType(program, type);
}

/**
 * Headers, parameters and the status code travel beside the body, and a `@body`/`@bodyRoot`
 * property *is* the body: a response envelope made only of these has no DTO of its own.
 */
function isHttpMetadata(program: Program, property: ModelProperty): boolean {
  return isMetadata(program, property) || isBody(program, property) || isBodyRoot(program, property);
}

function inheritedProperties(model: Model): ModelProperty[] {
  const byName = new Map<string, ModelProperty>();
  const lineage: Model[] = [];
  for (let current: Model | undefined = model; current; current = current.baseModel) {
    lineage.unshift(current);
  }
  for (const current of lineage) {
    for (const property of current.properties.values()) byName.set(property.name, property);
  }
  return [...byName.values()];
}

function renderEnum(_program: Program, enm: Enum): string {
  const enumMembers = [...enm.members.values()];
  const usesStringValues = enumMembers.some((m) => typeof m.value !== "number");
  const converter = usesStringValues
    ? `[JsonConverter(typeof(global::Nami.Api.Contracts.StringEnumConverter<${enm.name}>))]\n`
    : "";
  const members = enumMembers.map((m) => {
    const wireValue = typeof m.value === "string" ? m.value : m.name;
    const nameAttribute = usesStringValues
      ? `    [JsonStringEnumMemberName("${escapeCsharpString(wireValue)}")]\n`
      : "";
    const valueSuffix = typeof m.value === "number" ? ` = ${m.value}` : "";
    return `${nameAttribute}    ${pascal(m.name)}${valueSuffix}`;
  }).join(",\n");
  return `${converter}public enum ${enm.name}\n{\n${members}\n}\n${usesStringValues ? renderEnumValues(enumMembers, enm.name) : ""}`;
}

/**
 * A string enum's wire values as constants, the members of the TypeScript emitter's `<Enum>Values`, so a consumer
 * compares with the contract's value instead of a literal typed beside it.
 */
function renderEnumValues(members: EnumMember[], name: string): string {
  const constants = members.map((m) =>
    `    public const string ${pascal(m.name)} = "${escapeCsharpString(typeof m.value === "string" ? m.value : m.name)}";`);
  return `\npublic static class ${name}Values\n{\n${constants.join("\n")}\n}\n`;
}

function pascal(s: string): string {
  return s.length === 0 ? s : s[0].toUpperCase() + s.slice(1);
}

function escapeCsharpString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}
