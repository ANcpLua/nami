const HEADER = "﻿// <auto-generated/>\n// Copyright (c) 2025-2026 ancplua\n#nullable enable\n\nusing System.Linq;\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\n";

type Bucket = {
  namespace: string;
  scalars: Scalar[];
  models: Array<[Model, string]>;
  enums: Enum[];
  unions: Union[];
  mediaTypes: Map<string, string>;
};

export async function $onEmit(context: EmitContext): Promise<void> {
  const program = context.program;
  if (program.compilerOptions.noEmit) return;

  const buckets = new Map<string, Bucket>();
  const emittedNames = new Set<string>();

  navigateProgram(program, {
    model: (m) => {
      if (isInTypeSpec(m)) return;
      if (!m.name) return;
      const ns = resolveNamespace(program, m);
      if (!ns) return;
      collectMediaType(program, m, getBucket(buckets, ns));
      const hasBodyProperty = inheritedProperties(m)
        .some((property) => !isHttpMetadata(program, property));
      const isExplicitEmptyModel = m.properties.size === 0 && !m.baseModel;
      if (!hasBodyProperty && !isExplicitEmptyModel) return;
      // Template instantiations share the base name (`CursorPage`); use the instantiated
      // form `CursorPageTrace` so each instantiation produces a distinct type. Template
      // DEFINITIONS are not navigated, so this only fires on concrete instantiations.
      const emittedName = instantiationName(m);
      const key = `${ns}.${emittedName}`;
      if (emittedNames.has(key)) return;
      emittedNames.add(key);
      getBucket(buckets, ns).models.push([m, emittedName]);
    },
    enum: (e) => {
      if (isInTypeSpec(e)) return;
      const ns = resolveNamespace(program, e);
      if (!ns) return;
      getBucket(buckets, ns).enums.push(e);
    },
    union: (u) => {
      if (isInTypeSpec(u) || !u.name) return;
      if (!hasCsharpPolymorphic(program, u) && !isDiscriminatedUnion(program, u) && !mixedUnionShape(program, u)) return;
      const ns = resolveNamespace(program, u);
      if (!ns) return;
      getBucket(buckets, ns).unions.push(u);
    },
    scalar: (s) => {
      if (isInTypeSpec(s) || !s.name || !hasCsharpBrand(program, s)) return;
      const ns = resolveNamespace(program, s);
      if (!ns) return;
      getBucket(buckets, ns).scalars.push(s);
    },
  });

  const unions = [...buckets.values()].flatMap((bucket) => bucket.unions);
  const requestBodies = requestBodyModels(program);
  const requestModels = nestedModels(requestBodies);
  const routes = routeParameters(program);
  for (const [ns, bucket] of buckets) {
    const path = `${context.emitterOutputDir}/${ns.replace(/\./g, "/")}.cs`;
    const content = renderBucket(program, bucket, unions, requestModels);
    await emitFile(program, { path, content: ns === routes.namespace ? `${content}\n${routes.content}` : content });
  }
  const entries: Array<[string, string]> = [];
  for (const bucket of buckets.values()) {
    const internalBases = polymorphicBaseModels(bucket.unions);
    for (const [model, name] of bucket.models) {
      if (internalBases.has(model)) continue;
      entries.push([`${bucket.namespace}.${name}`, getFriendlyName(program, model) ?? `${getNamespaceFullName(model.namespace!)}.${name}`.replace(/^Nami\.Api\.Contracts\./u, "")]);
    }
    for (const union of bucket.unions) entries.push([`${bucket.namespace}.${union.name}`, `${getNamespaceFullName(union.namespace!)}.${union.name}`.replace(/^Nami\.Api\.Contracts\./u, "")]);
    for (const enm of bucket.enums) entries.push([`${bucket.namespace}.${enm.name}`, `${getNamespaceFullName(enm.namespace!)}.${enm.name}`.replace(/^Nami\.Api\.Contracts\./u, "")]);
  }
  entries.sort((a, b) => a[1].localeCompare(b[1]));
  const analysis = entries.filter(([, name]) => /^Mcp\.Tools\.\w+Input$/.test(name) && entries.some(([, output]) => output === name.replace(/Input$/, "Output")));
  const analysisCases = analysis.map(([, name]) => {
    const operation = name.slice("Mcp.Tools.".length, -"Input".length).replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
    return `        "${operation}" => ("${name}", "${name.replace(/Input$/, "Output")}"),`;
  }).join("\n");
  const [httpServices] = getAllHttpServices(program);
  const arrayBodies = new Set(httpServices.flatMap(service => service.operations).flatMap(operation => operation.responses)
    .flatMap(response => response.responses).map(response => response.body)
    .filter(body => body?.bodyKind === "single" && body.type.kind === "Model" && isArrayModelType(body.type))
    .map(body => `${mapType(program, (body!.type as Model).indexer!.value)}[]`));
  const generated = `// <auto-generated/>\n#nullable enable\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\nusing System.Text.Json.Serialization.Metadata;\nnamespace Nami.Api.Contracts;\n\npublic static class ContractTypes\n{\n    public static IJsonTypeInfoResolver Resolver => GeneratedContractJsonContext.Default;\n    public static JsonTypeInfo<T> TypeInfo<T>() => (JsonTypeInfo<T>)(GeneratedContractJsonContext.Default.GetTypeInfo(typeof(T)) ?? throw new ArgumentException($"No generated serializer for {typeof(T)}."));\n    public static (string Input, string Output) Analysis(string operation) => operation switch\n    {\n${analysisCases}\n        _ => throw new ArgumentException($"No generated analysis contract for {operation}.", nameof(operation))\n    };\n    public static string NameOf(Type type) => type switch\n    {\n${entries.map(([type, name]) => `        _ when type == typeof(global::${type}) => ${JSON.stringify(name)},`).join("\n")}\n        _ => throw new ArgumentException($"No generated contract for {type}.", nameof(type))\n    };\n    public static JsonTypeInfo TypeInfo(string name) => name switch\n    {\n${entries.map(([type, name]) => {
    const owner = unions.find(union => [...union.variants.values()].some(variant => variant.type.kind === "Model" && `${resolveNamespace(program, variant.type)}.${variant.type.name}` === type));
    const readAs = owner && !mixedUnionShape(program, owner) ? `${resolveNamespace(program, owner)}.${owner.name}` : type;
    return `        ${JSON.stringify(name)} => GeneratedContractJsonContext.Default.GetTypeInfo(typeof(global::${readAs}))!,`;
  }).join("\n")}\n        _ => throw new ArgumentException($"No generated serializer for {name}.", nameof(name))\n    };\n}\n\n[JsonSourceGenerationOptions(AllowOutOfOrderMetadataProperties = true, UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow)]\n[JsonSerializable(typeof(JsonElement))]\n${entries.map(([type]) => `[JsonSerializable(typeof(global::${type}))]`).join("\n")}\n${[...arrayBodies].map(type => `[JsonSerializable(typeof(global::${type}))]`).join("\n")}\ninternal partial class GeneratedContractJsonContext : JsonSerializerContext;\n`;
  await emitFile(program, { path: `${context.emitterOutputDir}/Nami/Api/Contracts/ContractTypes.cs`, content: generated });
}

/**
 * Every path and query parameter of the service's HTTP operations that the contract bounds by a length or a pattern,
 * by its operation's method and route, rendered in the service's namespace, so a server refuses a parameter outside
 * them from the contract, as it refuses a body member, whichever route takes it.
 */
function routeParameters(program: Program): { namespace: string | undefined; content: string } {
  const [services] = getAllHttpServices(program);
  const entries: string[] = [];
  const numbers: string[] = [];
  for (const operation of services.flatMap((service) => service.operations)) {
    for (const parameter of operation.parameters.parameters) {
      if (parameter.type !== "path" && parameter.type !== "query") continue;
      const property = parameter.param;
      const range = numericRange(program, property, mapType(program, property.type), true);
      if (range !== undefined) {
        const fallback = property.defaultValue?.valueKind === "NumericValue" ? property.defaultValue.value.toString() : "null";
        numbers.push(`        ("${operation.verb.toUpperCase()}", "${escapeCsharpString(operation.path)}", "${escapeCsharpString(parameter.name)}", new(${fallback}, ${range.minimum ?? "null"}, ${range.maximum ?? "null"})),`);
      }
      if (property.type.kind !== "Scalar" || !isStringScalar(property.type)) continue;
      const minimum = numericBound(program, property, getMinLength, true);
      const maximum = numericBound(program, property, getMaxLength, true);
      const pattern = getPattern(program, property) ?? scalarPattern(program, property.type);
      if (minimum === undefined && maximum === undefined && pattern === undefined) continue;
      entries.push(`        ("${operation.verb.toUpperCase()}", "${escapeCsharpString(operation.path)}", "${escapeCsharpString(parameter.name)}", "${parameter.type}", ${minimum ?? "null"}, ${maximum ?? "null"}, ${pattern === undefined ? "null" : `"${escapeCsharpString(pattern)}"`}),`);
    }
  }
  const service = services.find(() => true)?.namespace;
  return {
    namespace: service === undefined ? undefined : getCsharpNamespace(program, service),
    content: "/// <summary>\n/// Each path and query parameter of an HTTP operation the contract bounds, by the operation's method and route: where it\n"
      + "/// travels, the characters it keeps, counted as code points, and the ECMAScript pattern it matches, as JSON Schema's\n"
      + "/// pattern reads it.\n/// </summary>\n"
      + "public static class RouteParameters\n{\n"
      + "    public static readonly IReadOnlyList<(string Method, string Route, string Name, string In, int? MinLength, int? MaxLength, string? Pattern)> All =\n"
      + `    [${entries.length === 0 ? "" : `\n${entries.join("\n")}\n    `}];\n`
      + "    public readonly record struct NumericParameter(double? Default, double? Minimum, double? Maximum);\n"
      + "    private static readonly (string Method, string Route, string Name, NumericParameter Value)[] Numbers =\n"
      + `    [${numbers.length === 0 ? "" : `\n${numbers.join("\n")}\n    `}];\n`
      + "    public static NumericParameter Number(string method, string route, string name) => Numbers.Single(item => item.Method == method && item.Route == route && item.Name == name).Value;\n}\n",
  };
}

/** The models an HTTP operation takes as its request body. */
function requestBodyModels(program: Program): Set<Model> {
  const [services] = getAllHttpServices(program);
  return new Set(services.flatMap((service) => service.operations)
    .map((operation) => operation.parameters.body?.type)
    .filter((type): type is Model => type?.kind === "Model"));
}

/** The models a request body holds at any depth, in its unions and arrays and itself included. */
function nestedModels(bodies: Set<Model>): Set<Model> {
  const found = new Set<Model>();
  const visit = (type: Type): void => {
    if (type.kind === "Union") for (const variant of type.variants.values()) visit(variant.type);
    if (type.kind !== "Model") return;
    if (isArrayModelType(type) || isRecordModelType(type)) return visit(type.indexer!.value);
    if (found.has(type)) return;
    found.add(type);
    for (const property of inheritedProperties(type)) visit(property.type);
  };
  for (const body of bodies) visit(body);
  return found;
}

function instantiationName(model: Model): string {
  if (!model.templateMapper?.args.length) return model.name;
  const parts = [model.name];
  for (const arg of model.templateMapper.args) {
    if ("kind" in arg && "name" in arg && typeof arg.name === "string") {
      parts.push(pascal(arg.name));
    }
  }
  return parts.join("");
}

function isInTypeSpec(type: { namespace?: { name?: string; namespace?: unknown } }): boolean {
  let cursor: { name?: string; namespace?: unknown } | undefined = type.namespace;
  while (cursor) {
    if (cursor.name === "TypeSpec") return true;
    cursor = cursor.namespace as typeof cursor;
  }
  return false;
}

function getBucket(buckets: Map<string, Bucket>, namespace: string): Bucket {
  let b = buckets.get(namespace);
  if (!b) {
    b = { namespace, scalars: [], models: [], enums: [], unions: [], mediaTypes: new Map() };
    buckets.set(namespace, b);
  }
  return b;
}

function resolveNamespace(program: Program, type: Model | Enum | Scalar | Union): string | undefined {
  const own = getCsharpNamespace(program, type);
  if (own) return own;
  let cursor = type.namespace;
  while (cursor) {
    const mapped = getCsharpNamespace(program, cursor);
    if (mapped) return mapped;
    cursor = cursor.namespace;
  }
  return undefined;
}

function renderBucket(program: Program, bucket: Bucket, unions: Union[], requestModels: Set<Model>): string {
  const out: string[] = [HEADER];
  out.push(`namespace ${bucket.namespace};\n`);
  for (const scalar of bucket.scalars) out.push(renderBrandedScalar(scalar));
  for (const [name, value] of bucket.mediaTypes) out.push(renderMediaType(name, value));
  for (const union of bucket.unions) {
    const mixed = mixedUnionShape(program, union);
    out.push(mixed ? renderMixedUnion(program, union, mixed) : renderPolymorphicUnion(program, union));
  }
  const internalBases = polymorphicBaseModels(bucket.unions);
  for (const [m, name] of bucket.models) {
    if (!internalBases.has(m)) out.push(renderModel(program, m, name, unions, requestModels.has(m)));
  }
  for (const e of bucket.enums) out.push(renderEnum(program, e));
  return out.join("\n");
}

function renderBrandedScalar(scalar: Scalar): string {
  if (!isStringScalar(scalar)) {
    throw new Error(`@csharpBrand scalar '${scalar.name}' must extend string.`);
  }
  const name = scalar.name;
  const converter = `${name}JsonConverter`;
  return `[JsonConverter(typeof(${converter}))]\npublic readonly record struct ${name}(string Value)\n{\n    public override string ToString() => Value;\n}\n\npublic sealed class ${converter} : JsonConverter<${name}>\n{\n    public override ${name} Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)\n    {\n        if (reader.TokenType != JsonTokenType.String) throw new JsonException("${name} must be a JSON string.");\n        return new ${name}(reader.GetString() ?? throw new JsonException("${name} cannot be null."));\n    }\n\n    public override void Write(Utf8JsonWriter writer, ${name} value, JsonSerializerOptions options) =>\n        writer.WriteStringValue(value.Value);\n}\n`;
}

function isStringScalar(scalar: Scalar): boolean {
  if (scalar.name === "string") return true;
  return scalar.baseScalar ? isStringScalar(scalar.baseScalar) : false;
}

function polymorphicBaseModels(unions: Union[]): Set<Model> {
  const result = new Set<Model>();
  for (const union of unions) {
    for (const variant of union.variants.values()) {
      if (variant.type.kind === "Model" && variant.type.baseModel) result.add(variant.type.baseModel);
    }
  }
  return result;
}

/**
 * A model that declares its own `@mediaTypeHint` (ProblemDetails) gets a constant for it, so a
 * server writes the published media type instead of a string typed beside it. Derived models
 * inherit the hint and do not repeat the constant.
 */
function collectMediaType(program: Program, model: Model, bucket: Bucket): void {
  const hint = getMediaTypeHint(program, model);
  if (hint === undefined) return;
  if (model.baseModel && getMediaTypeHint(program, model.baseModel) === hint) return;
  bucket.mediaTypes.set(`${model.name}MediaType`, hint);
}

function renderMediaType(name: string, value: string): string {
  return `public static class ${name}\n{\n    public const string Value = "${escapeCsharpString(value)}";\n}\n`;
}

/** The wire discriminator of a tagged union and the tag each variant model carries. */
function taggedUnionInfo(program: Program, union: Union): { property: string; tagOf: (model: Model) => string } | undefined {
  const [discriminated] = getDiscriminatedUnion(program, union);
  if (discriminated) {
    if (discriminated.options.envelope !== "none") {
      throw new Error(`@discriminated union '${union.name}' must use envelope "none"; the emitter has no envelope form.`);
    }
    const tags = new Map<Type, string>();
    for (const [name, type] of discriminated.variants) tags.set(type, name);
    return {
      property: discriminated.options.discriminatorPropertyName,
      tagOf: (model) => {
        const tag = tags.get(model);
        if (tag === undefined) throw new Error(`Model '${model.name}' is not a variant of '${union.name}'.`);
        return tag;
      },
    };
  }
  const property = getCsharpPolymorphicDiscriminator(program, union);
  if (!property) return undefined;
  return {
    property,
    tagOf: (model) => {
      const literal = inheritedProperties(model).find((candidate) =>
        resolveEncodedName(program, candidate, "application/json") === property,
      );
      if (!literal || literal.type.kind !== "String") {
        throw new Error(
          `@csharpPolymorphic union '${union.name}' variant '${model.name}' must have literal string '${property}'.`,
        );
      }
      return literal.type.value;
    },
  };
}

function renderModel(program: Program, model: Model, emittedName: string, unions: Union[], requestModel: boolean): string {
  const keyword = "public sealed class";
  const memberships = unions.filter((candidate) =>
    !mixedUnionShape(program, candidate) &&
    [...candidate.variants.values()].some((variant) => variant.type === model),
  );
  const implementsUnion = memberships.length
    ? ` : ${memberships.map((union) => localOrQualifiedType(program, model, union)).join(", ")}` : "";
  const discriminators = new Set(memberships.map((union) => taggedUnionInfo(program, union)?.property));
  const constants: string[] = [];
  const props: string[] = [];
  for (const prop of inheritedProperties(model)) {
    if (isHttpMetadata(program, prop)) continue;
    const jsonName = escapeCsharpString(resolveEncodedName(program, prop, "application/json"));
    if (discriminators.has(jsonName)) continue;
    const type = mapType(program, prop.type);
    const name = pascal(prop.name);
    constants.push(...renderConstants(program, prop, type.replace(/\?$/, ""), name, requestModel));
    const numberHandling = renderNumberHandling(program, prop);
    if (prop.optional && type.endsWith("?")) {
      props.push(`    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]\n    [JsonConverter(typeof(global::Nami.Api.Contracts.OptionalValueConverter<${type}>))]\n    [JsonPropertyName("${jsonName}")]\n    public global::Nami.Api.Contracts.OptionalValue<${type}> ${name} { get; init; }`);
    } else if (prop.optional) {
      const optionalType = `${type}?`;
      const ignoreNull = "    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]\n";
      props.push(`${numberHandling}${ignoreNull}    [JsonPropertyName("${jsonName}")]\n    public ${optionalType} ${name} { get; init; }`);
    } else {
      // A required property whose type admits null must be written even when null; a consumer's
      // context-wide WhenWritingNull policy would otherwise drop it and fail its own reader.
      const alwaysWrite = type.endsWith("?") ? "    [JsonIgnore(Condition = JsonIgnoreCondition.Never)]\n" : "";
      props.push(`${numberHandling}${alwaysWrite}    [JsonPropertyName("${jsonName}")]\n    public required ${type} ${name} { get; init; }`);
    }
  }
  const members = [...constants, ...props];
  const body = members.length ? `\n${members.join("\n")}\n` : "\n";
  return `${keyword} ${emittedName}${implementsUnion}\n{${body}}\n`;
}

const NUMERIC_CS_TYPES = new Set(["sbyte", "byte", "short", "ushort", "int", "uint", "long", "ulong", "float", "double", "decimal"]);

/**
 * A property's declared default and its declared numeric range become constants beside it, so a
 * consumer applies the contract's defaults and bounds from these generated values instead of
 * restating them. A range is the property's own, or for a property with a default or of a model a
 * request body holds its scalar's.
 */
function renderConstants(program: Program, property: ModelProperty, type: string, name: string, requestModel: boolean): string[] {
  const lines: string[] = [];
  const fallback = defaultLiteral(property, type);
  if (fallback !== undefined) lines.push(`    public const ${type} ${name}Default = ${fallback};`);
  const range = numericRange(program, property, type, requestModel || fallback !== undefined);
  if (range?.minimum !== undefined) lines.push(`    public const ${type} ${name}Minimum = ${numericLiteral(String(range.minimum), type)};`);
  if (range?.maximum !== undefined) lines.push(`    public const ${type} ${name}Maximum = ${numericLiteral(String(range.maximum), type)};`);
  return lines;
}

/** A numeric property's declared bounds, a scalar's included where `scalar`; undefined when it has none. */
function numericRange(program: Program, property: ModelProperty, type: string, scalar: boolean): { minimum?: number; maximum?: number } | undefined {
  if (!NUMERIC_CS_TYPES.has(type)) return undefined;
  const minimum = numericBound(program, property, getMinValue, scalar);
  const maximum = numericBound(program, property, getMaxValue, scalar);
  return minimum === undefined && maximum === undefined ? undefined : { minimum, maximum };
}

function scalarBound(program: Program, scalar: Scalar, read: (program: Program, target: Type) => number | undefined): number | undefined {
  for (let current: Scalar | undefined = scalar; current; current = current.baseScalar) {
    const bound = read(program, current);
    if (bound !== undefined) return bound;
  }
  return undefined;
}

/**
 * A request body's bounded strings and arrays in one list, so a server rejects a sent value of another length from
 * the contract, whichever operation takes the body.
 */
function scalarPattern(program: Program, scalar: Scalar): string | undefined {
  for (let current: Scalar | undefined = scalar; current; current = current.baseScalar) {
    const pattern = getPattern(program, current);
    if (pattern !== undefined) return pattern;
  }
  return undefined;
}

/**
 * A request body's patterned strings in one list, so a server refuses a sent value that does not match from the contract,
 * whichever operation takes the body.
 */
function defaultLiteral(property: ModelProperty, type: string): string | undefined {
  const value = property.defaultValue;
  switch (value?.valueKind) {
    case "NumericValue":
      return NUMERIC_CS_TYPES.has(type) ? numericLiteral(value.value.toString(), type) : undefined;
    case "StringValue":
      return type === "string" ? `"${escapeCsharpString(value.value)}"` : undefined;
    case "BooleanValue":
      return type === "bool" ? String(value.value) : undefined;
    case "EnumValue":
      return `${type}.${pascal(value.value.name)}`;
    default:
      return undefined;
  }
}

function numericBound(
  program: Program,
  property: ModelProperty,
  read: (program: Program, target: Type) => number | undefined,
  includeScalar: boolean,
): number | undefined {
  const own = read(program, property);
  if (own !== undefined || !includeScalar) return own;
  for (let scalar = property.type.kind === "Scalar" ? property.type as Scalar : undefined; scalar; scalar = scalar.baseScalar) {
    const bound = read(program, scalar);
    if (bound !== undefined) return bound;
  }
  return undefined;
}

function numericLiteral(text: string, type: string): string {
  return type === "float" ? `${text}f` : type === "decimal" ? `${text}m` : text;
}

function renderNumberHandling(program: Program, property: ModelProperty): string {
  if (isStringEncodedNumber(program, property)) {
    const type = mapType(program, property.type).replace(/\?$/u, "");
    if (type === "long" || type === "ulong") return `    [JsonConverter(typeof(global::Nami.Api.Contracts.${type === "long" ? "Int64" : "UInt64"}StringConverter))]\n`;
    if (type === "IReadOnlyList<ulong>" || type === "IReadOnlyList<long>") return `    [JsonConverter(typeof(global::Nami.Api.Contracts.IntegerStringListConverter<${type === "IReadOnlyList<ulong>" ? "ulong" : "long"}>))]\n`;
    throw new Error(`String encoding needs a converter for ${type}.`);
  }
  if (hasNamedFloatingPointValues(property.type)) {
    return "    [JsonNumberHandling(JsonNumberHandling.AllowNamedFloatingPointLiterals)]\n";
  }
  return "";
}

function hasNamedFloatingPointValues(type: Type): boolean {
  if (isNamedFloatingPointUnion(type)) return true;
  if (type.kind === "Model" && isArrayModelType(type)) return hasNamedFloatingPointValues(type.indexer!.value);
  if (type.kind === "Union") {
    const nonNull = [...type.variants.values()].map((variant) => variant.type)
      .filter((member) => member.kind !== "Intrinsic" || member.name !== "null");
    return nonNull.length === 1 && hasNamedFloatingPointValues(nonNull[0]!);
  }
  return false;
}

function isStringEncodedNumber(program: Program, property: ModelProperty): boolean {
  const direct = getEncode(program, property);
  if (direct?.type.name === "string") return isNumericType(property.type);
  return hasStringEncodedNumericScalar(program, property.type);
}

function hasStringEncodedNumericScalar(program: Program, type: Type): boolean {
  if (type.kind === "Scalar") {
    const scalar = type as Scalar;
    if (getEncode(program, scalar)?.type.name === "string") return isNumericScalar(scalar);
    return scalar.baseScalar ? hasStringEncodedNumericScalar(program, scalar.baseScalar) : false;
  }
  if (type.kind === "Model" && isArrayModelType(type)) {
    return hasStringEncodedNumericScalar(program, type.indexer!.value);
  }
  return false;
}

function isNumericType(type: Type): boolean {
  if (type.kind === "Scalar") return isNumericScalar(type as Scalar);
  return type.kind === "Model" && isArrayModelType(type) && isNumericType(type.indexer!.value);
}

function isNumericScalar(scalar: Scalar): boolean {
  if (["int8", "int16", "int32", "int64", "uint8", "uint16", "uint32", "uint64", "float32", "float64", "decimal", "decimal128"].includes(scalar.name)) {
    return true;
  }
  return scalar.baseScalar ? isNumericScalar(scalar.baseScalar) : false;
}

function renderPolymorphicUnion(program: Program, union: Union): string {
  const variants = [...union.variants.values()].map((variant) => {
    if (variant.type.kind !== "Model") {
      throw new Error(`@csharpPolymorphic union '${union.name}' contains non-model variant '${String(variant.name)}'.`);
    }
    return variant.type;
  });
  const tagged = taggedUnionInfo(program, union);
  if (tagged) {
    const attributes = variants.map((model) =>
      `[JsonDerivedType(typeof(${localOrQualifiedType(program, union, model)}), "${escapeCsharpString(tagged.tagOf(model))}")]`,
    );
    // The tag is a plain property on the wire. System.Text.Json reads it first by default; a
    // consumer that receives it in any position sets AllowOutOfOrderMetadataProperties on its
    // serializer options (or JsonSourceGenerationOptions).
    return `[JsonPolymorphic(TypeDiscriminatorPropertyName = "${escapeCsharpString(tagged.property)}")]\n${attributes.join("\n")}\npublic interface ${union.name}\n{\n}\n`;
  }

  const selectors = variants.map((model) => {
    const property = [...model.properties.values()].find((candidate) =>
      !candidate.optional && !isHttpMetadata(program, candidate),
    );
    if (!property) {
      throw new Error(
        `@csharpPolymorphic union '${union.name}' variant '${model.name}' needs a required distinguishing property.`,
      );
    }
    return {
      model,
      wireName: resolveEncodedName(program, property, "application/json"),
    };
  });
  const converter = `${union.name}JsonConverter`;
  const presence = selectors.map(({ model, wireName }) =>
    `        var has${model.name} = root.TryGetProperty("${escapeCsharpString(wireName)}", out _);`,
  ).join("\n");
  const count = selectors.map(({ model }) => `(has${model.name} ? 1 : 0)`).join(" + ");
  // GetTypeInfo-based overloads keep the converter trim/AOT-warning-free (IL2026/IL3050): the
  // reflection-annotated Serialize<T>/Deserialize<T>(options) overloads warn statically even when
  // the options carry a source-gen resolver at runtime.
  const reads = selectors.map(({ model }) =>
    `        if (has${model.name}) return (${model.name}?)root.Deserialize(options.GetTypeInfo(typeof(${model.name})));`,
  ).join("\n");
  const writes = selectors.map(({ model }) =>
    `            case ${model.name} typed:\n                JsonSerializer.Serialize(writer, typed, options.GetTypeInfo(typeof(${model.name})));\n                return;`,
  ).join("\n");
  return `[JsonConverter(typeof(${converter}))]\npublic interface ${union.name}\n{\n}\n\npublic sealed class ${converter} : JsonConverter<${union.name}>\n{\n    public override ${union.name}? Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)\n    {\n        if (reader.TokenType == JsonTokenType.Null) return null;\n        using var document = JsonDocument.ParseValue(ref reader);\n        var root = document.RootElement;\n        if (root.ValueKind != JsonValueKind.Object) throw new JsonException("${union.name} must be a JSON object.");\n${presence}\n        if (${count} != 1) throw new JsonException("${union.name} must contain exactly one variant field.");\n${reads}\n        throw new JsonException("${union.name} did not match a known variant.");\n    }\n\n    public override void Write(Utf8JsonWriter writer, ${union.name} value, JsonSerializerOptions options)\n    {\n        switch (value)\n        {\n${writes}\n            default:\n                throw new JsonException($"Unknown ${union.name} implementation '{value.GetType().FullName}'.");\n        }\n    }\n}\n`;
}

function localOrQualifiedType(program: Program, owner: Model | Union, type: Model | Union): string {
  if (!type.name) throw new Error("A polymorphic model or union must have an emitted name.");
  return resolveNamespace(program, owner) === resolveNamespace(program, type) ? type.name : mapType(program, type);
}

/**
 * A union of bare JSON primitives plus one tagged object member becomes an abstract class with
 * one sealed case per primitive kind and one wrapping the object member, plus a converter that
 * dispatches on the JSON token kind. The object member keeps its own discriminator converter.
 */
function renderMixedUnion(program: Program, union: Union, shape: MixedUnionShape): string {
  const name = union.name!;
  const converter = `${name}JsonConverter`;
  const objectType = mapType(program, shape.objectMember!.type);
  const caseName = (variantName: string) => pascal(variantName);
  const variantNames = new Map<string, string>();
  for (const [variantName, variant] of union.variants) {
    const t = variant.type;
    const key = t.kind === "Intrinsic" ? "null"
      : t.kind === "Scalar" ? mapType(program, t)
      : t.kind === "Model" && isArrayModelType(t) ? "array"
      : "object";
    variantNames.set(key, caseName(String(variantName)));
  }
  const stringCase = shape.primitives.includes("string") ? variantNames.get("string") : undefined;
  const boolCase = shape.primitives.includes("boolean") ? variantNames.get("bool") : undefined;
  const numberCase = shape.primitives.includes("number") ? [...variantNames.entries()].find(([k]) => k !== "string" && k !== "bool" && k !== "null" && k !== "array" && k !== "object")?.[1] : undefined;
  const arrayCase = shape.arrayOfSelf ? variantNames.get("array") : undefined;
  const objectCase = variantNames.get("object")!;
  const elementType = `${name}${shape.hasNull ? "?" : ""}`;

  const cases: string[] = [];
  const reads: string[] = [];
  const writes: string[] = [];
  if (stringCase) {
    cases.push(`    public sealed class ${stringCase}(string value) : ${name}\n    {\n        public string Value { get; } = value;\n    }`);
    reads.push(`            case JsonTokenType.String:\n                return new ${name}.${stringCase}(reader.GetString()!);`);
    writes.push(`            case ${name}.${stringCase} typed:\n                writer.WriteStringValue(typed.Value);\n                return;`);
  }
  if (boolCase) {
    cases.push(`    public sealed class ${boolCase}(bool value) : ${name}\n    {\n        public bool Value { get; } = value;\n    }`);
    reads.push(`            case JsonTokenType.True:\n            case JsonTokenType.False:\n                return new ${name}.${boolCase}(reader.GetBoolean());`);
    writes.push(`            case ${name}.${boolCase} typed:\n                writer.WriteBooleanValue(typed.Value);\n                return;`);
  }
  if (numberCase) {
    cases.push(`    public sealed class ${numberCase}(double value) : ${name}\n    {\n        public double Value { get; } = value;\n    }`);
    reads.push(`            case JsonTokenType.Number:\n                return new ${name}.${numberCase}(reader.GetDouble());`);
    writes.push(`            case ${name}.${numberCase} typed:\n                writer.WriteNumberValue(typed.Value);\n                return;`);
  }
  if (arrayCase) {
    cases.push(`    public sealed class ${arrayCase}(IReadOnlyList<${elementType}> value) : ${name}\n    {\n        public IReadOnlyList<${elementType}> Value { get; } = value;\n    }`);
    reads.push(`            case JsonTokenType.StartArray:\n            {\n                var items = new List<${elementType}>();\n                while (reader.Read() && reader.TokenType != JsonTokenType.EndArray)\n                {\n                    items.Add(Read(ref reader, typeToConvert, options)${shape.hasNull ? "" : ` ?? throw new JsonException("${name} array items cannot be null.")`});\n                }\n                return new ${name}.${arrayCase}(items);\n            }`);
    writes.push(`            case ${name}.${arrayCase} typed:\n                writer.WriteStartArray();\n                foreach (var item in typed.Value)\n                {\n                    if (item is null) writer.WriteNullValue();\n                    else Write(writer, item, options);\n                }\n                writer.WriteEndArray();\n                return;`);
  }
  cases.push(`    public sealed class ${objectCase}(${objectType} value) : ${name}\n    {\n        public ${objectType} Value { get; } = value;\n    }`);
  const stable = renderStableString(program, name, shape, { stringCase, boolCase, numberCase, arrayCase, objectCase });
  // GetTypeInfo keeps the converter trim/AOT-warning-free; the consumer registers the member
  // type in its JsonSerializerContext, as it already does for every contract type it reads.
  reads.push(`            case JsonTokenType.StartObject:\n            {\n                var value = (${objectType}?)JsonSerializer.Deserialize(ref reader, options.GetTypeInfo(typeof(${objectType})));\n                return value is null ? null : new ${name}.${objectCase}(value);\n            }`);
  writes.push(`            case ${name}.${objectCase} typed:\n                JsonSerializer.Serialize(writer, typed.Value, options.GetTypeInfo(typeof(${objectType})));\n                return;`);

  return `[JsonConverter(typeof(${converter}))]\npublic abstract class ${name}\n{\n    private protected ${name}()\n    {\n    }\n\n${cases.join("\n\n")}\n\n${stable}\n}\n\npublic sealed class ${converter} : JsonConverter<${name}>\n{\n    public override ${name}? Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)\n    {\n        switch (reader.TokenType)\n        {\n            case JsonTokenType.Null:\n                return null;\n${reads.join("\n")}\n            default:\n                throw new JsonException($"${name} cannot start with token '{reader.TokenType}'.");\n        }\n    }\n\n    public override void Write(Utf8JsonWriter writer, ${name} value, JsonSerializerOptions options)\n    {\n        switch (value)\n        {\n${writes.join("\n")}\n            default:\n                throw new JsonException($"Unknown ${name} case '{value.GetType().FullName}'.");\n        }\n    }\n}\n`;
}

/**
 * The canonical text of a value: its wire JSON with every object's keys in ordinal order and
 * numbers in ECMAScript Number::toString form, so it is byte-identical to `JSON.stringify` of
 * the same value with sorted keys in the TypeScript runtime (`attributeIdentity`). One identity
 * for every language that reads the contract.
 */
function renderStableString(
  program: Program,
  name: string,
  shape: MixedUnionShape,
  cases: { stringCase?: string; boolCase?: string; numberCase?: string; arrayCase?: string; objectCase: string },
): string {
  const member = shape.objectMember!;
  const variantWriters: string[] = [];
  if (member.type.kind === "Union") {
    const [discriminated] = getDiscriminatedUnion(program, member.type);
    const tagProperty = discriminated!.options.discriminatorPropertyName;
    for (const [tag, variantType] of discriminated!.variants) {
      if (variantType.kind !== "Model") continue;
      const modelName = mapType(program, variantType);
      const entries: Array<{ key: string; write: string }> = [
        { key: tagProperty, write: `writer.WriteStringValue("${escapeCsharpString(tag)}");` },
      ];
      for (const property of inheritedProperties(variantType)) {
        if (isHttpMetadata(program, property)) continue;
        const key = resolveEncodedName(program, property, "application/json");
        if (key === tagProperty) continue;
        const csType = mapType(program, property.type);
        const expr = `typed.${pascal(property.name)}`;
        entries.push({ key, write: stableWriteFor(program, property, csType, expr, name) });
      }
      entries.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
      variantWriters.push(
        `            case ${modelName} typed:\n                writer.WriteStartObject();\n` +
        entries.map((e) => `                writer.WritePropertyName("${escapeCsharpString(e.key)}");\n                ${e.write}`).join("\n") +
        `\n                writer.WriteEndObject();\n                return;`,
      );
    }
  }
  const primitiveCases: string[] = [];
  if (cases.stringCase) primitiveCases.push(`            case ${name}.${cases.stringCase} typed:\n                writer.WriteStringValue(typed.Value);\n                return;`);
  if (cases.boolCase) primitiveCases.push(`            case ${name}.${cases.boolCase} typed:\n                writer.WriteBooleanValue(typed.Value);\n                return;`);
  if (cases.numberCase) primitiveCases.push(`            case ${name}.${cases.numberCase} typed:\n                WriteJsNumber(writer, typed.Value);\n                return;`);
  if (cases.arrayCase) primitiveCases.push(`            case ${name}.${cases.arrayCase} typed:\n                writer.WriteStartArray();\n                foreach (var item in typed.Value) WriteStable(writer, item);\n                writer.WriteEndArray();\n                return;`);
  return `    /// <summary>
    /// The canonical text of this value: its wire JSON with every object's keys in ordinal order and
    /// numbers in ECMAScript form. Byte-identical to the TypeScript runtime's attributeIdentity, so an
    /// identity computed in either language is the same string.
    /// </summary>
    public string ToStableString()
    {
        var buffer = new System.Buffers.ArrayBufferWriter<byte>();
        using (var writer = new Utf8JsonWriter(buffer, new JsonWriterOptions { Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping }))
        {
            WriteStable(writer, this);
        }

        return System.Text.Encoding.UTF8.GetString(buffer.WrittenSpan);
    }

    /// <summary>The canonical text of a possibly-empty value; the empty value is <c>null</c>.</summary>
    public static string StableString(${name}? value) => value is null ? "null" : value.ToStableString();

    private static void WriteStable(Utf8JsonWriter writer, ${name}? value)
    {
        switch (value)
        {
            case null:
                writer.WriteNullValue();
                return;
${primitiveCases.join("\n")}
            case ${name}.${cases.objectCase} typed:
                WriteStableObject(writer, typed.Value);
                return;
            default:
                throw new InvalidOperationException($"Unknown ${name} case '{value.GetType().FullName}'.");
        }
    }

    private static void WriteStableObject(Utf8JsonWriter writer, ${mapType(program, member.type)} value)
    {
        switch (value)
        {
${variantWriters.join("\n")}
            default:
                throw new InvalidOperationException($"Unknown ${mapType(program, member.type)} variant '{value.GetType().FullName}'.");
        }
    }

    /// <summary>A double as ECMAScript Number::toString prints it, so both languages agree on identity.</summary>
    private static void WriteJsNumber(Utf8JsonWriter writer, double value)
    {
        if (double.IsNaN(value)) { writer.WriteStringValue("NaN"); return; }
        if (double.IsPositiveInfinity(value)) { writer.WriteStringValue("Infinity"); return; }
        if (double.IsNegativeInfinity(value)) { writer.WriteStringValue("-Infinity"); return; }
        if (value == 0) { writer.WriteRawValue("0", skipInputValidation: true); return; }
        var negative = value < 0;
        var round = Math.Abs(value).ToString("R", System.Globalization.CultureInfo.InvariantCulture);
        var exponentIndex = round.IndexOfAny(['E', 'e']);
        var mantissa = exponentIndex < 0 ? round : round[..exponentIndex];
        var exponent = exponentIndex < 0 ? 0 : int.Parse(round[(exponentIndex + 1)..], System.Globalization.CultureInfo.InvariantCulture);
        var pointIndex = mantissa.IndexOf('.');
        var integerPart = pointIndex < 0 ? mantissa : mantissa[..pointIndex];
        var fraction = pointIndex < 0 ? "" : mantissa[(pointIndex + 1)..];
        var digits = (integerPart + fraction).TrimStart('0');
        var n = integerPart.TrimStart('0').Length + exponent;
        if (integerPart.TrimStart('0').Length == 0)
        {
            var leadingZeros = fraction.Length - fraction.TrimStart('0').Length;
            n = -leadingZeros + exponent;
        }

        digits = digits.TrimEnd('0');
        var k = digits.Length;
        string text;
        if (k <= n && n <= 21) text = digits + new string('0', n - k);
        else if (0 < n && n <= 21) text = digits[..n] + "." + digits[n..];
        else if (-6 < n && n <= 0) text = "0." + new string('0', -n) + digits;
        else
        {
            var e = n - 1;
            var sign = e >= 0 ? "+" : "-";
            text = (k == 1 ? digits : digits[..1] + "." + digits[1..]) + "e" + sign + Math.Abs(e).ToString(System.Globalization.CultureInfo.InvariantCulture);
        }

        writer.WriteRawValue((negative ? "-" : "") + text, skipInputValidation: true);
    }
`;
}

/** How one property of a tagged variant is written in canonical form, by its C# type. */
function stableWriteFor(program: Program, property: ModelProperty, csType: string, expr: string, unionName: string): string {
  if (csType === "string") return `writer.WriteStringValue(${expr});`;
  if (csType === "bool") return `writer.WriteBooleanValue(${expr});`;
  if (csType === "long" || csType === "int" || csType === "short" || csType === "ulong" || csType === "uint") {
    // Integers that travel as strings on the wire (@encode(string)) stay strings in the canonical text.
    return isStringEncodedNumber(program, property)
      ? `writer.WriteStringValue(${expr}.ToString(System.Globalization.CultureInfo.InvariantCulture));`
      : `writer.WriteRawValue(${expr}.ToString(System.Globalization.CultureInfo.InvariantCulture), skipInputValidation: true);`;
  }
  if (csType === "double" || csType === "float") return `WriteJsNumber(writer, ${expr});`;
  if (csType === "ReadOnlyMemory<byte>") return `writer.WriteStringValue(Convert.ToBase64String(${expr}.Span));`;
  if (csType.startsWith("IReadOnlyDictionary<string, ")) {
    return `writer.WriteStartObject();\n                foreach (var (key, nested) in ${expr}.OrderBy(static item => item.Key, StringComparer.Ordinal)) { writer.WritePropertyName(key); WriteStable(writer, nested); }\n                writer.WriteEndObject();`;
  }
  if (csType.startsWith("IReadOnlyList<")) {
    return `writer.WriteStartArray();\n                foreach (var item in ${expr}) WriteStable(writer, item);\n                writer.WriteEndArray();`;
  }
  throw new Error(`Canonical text of ${unionName}: no stable writer for property '${property.name}' of C# type '${csType}'.`);
}

/**
 * Headers, parameters and the status code travel beside the body, and a `@body`/`@bodyRoot`
 * property *is* the body: a response envelope made only of these has no DTO of its own.
 */
function isHttpMetadata(program: Program, property: ModelProperty): boolean {
  return isMetadata(program, property) || isBody(program, property) || isBodyRoot(program, property);
}

function inheritedProperties(model: Model): ModelProperty[] {
  const byName = new Map<string, ModelProperty>();
  const lineage: Model[] = [];
  for (let current: Model | undefined = model; current; current = current.baseModel) {
    lineage.unshift(current);
  }
  for (const current of lineage) {
    for (const property of current.properties.values()) byName.set(property.name, property);
  }
  return [...byName.values()];
}

function renderEnum(_program: Program, enm: Enum): string {
  const enumMembers = [...enm.members.values()];
  const usesStringValues = enumMembers.some((m) => typeof m.value !== "number");
  const converter = usesStringValues
    ? `[JsonConverter(typeof(global::Nami.Api.Contracts.StringEnumConverter<${enm.name}>))]\n`
    : "";
  const members = enumMembers.map((m) => {
    const wireValue = typeof m.value === "string" ? m.value : m.name;
    const nameAttribute = usesStringValues
      ? `    [JsonStringEnumMemberName("${escapeCsharpString(wireValue)}")]\n`
      : "";
    const valueSuffix = typeof m.value === "number" ? ` = ${m.value}` : "";
    return `${nameAttribute}    ${pascal(m.name)}${valueSuffix}`;
  }).join(",\n");
  return `${converter}public enum ${enm.name}\n{\n${members}\n}\n${usesStringValues ? renderEnumValues(enumMembers, enm.name) : ""}`;
}

/**
 * A string enum's wire values as constants, the members of the TypeScript emitter's `<Enum>Values`, so a consumer
 * compares with the contract's value instead of a literal typed beside it.
 */
function renderEnumValues(members: EnumMember[], name: string): string {
  const constants = members.map((m) =>
    `    public const string ${pascal(m.name)} = "${escapeCsharpString(typeof m.value === "string" ? m.value : m.name)}";`);
  return `\npublic static class ${name}Values\n{\n${constants.join("\n")}\n}\n`;
}

function pascal(s: string): string {
  return s.length === 0 ? s : s[0].toUpperCase() + s.slice(1);
}

function escapeCsharpString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}
