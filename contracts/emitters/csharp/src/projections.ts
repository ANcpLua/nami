import { recordOutput } from "./semantics.js";
import type { DecoratorContext, Model, ModelProperty, Namespace, Program, Type, Union } from "@typespec/compiler";
import { emitFile, isArrayModelType, isRecordModelType, walkPropertiesInherited } from "@typespec/compiler";
import { resolve } from "node:path";
import { stateKeys } from "./lib.js";
import { mapType } from "./type-map.js";
import { outputFor } from "./outputs.js";
type ProjectionFile = {directory: string; namespace: string; methods: string[]};
function appendProjection(program: Program, files: Map<string, ProjectionFile>, target: Model | Namespace, method: string): void {
  const output = outputFor(program, target);
  if (!output) throw new Error(`${target.name} requires an output profile`);
  const key = `${output.directory}:${output.namespace}`;
  const file = files.get(key) ?? {directory: output.directory, namespace: output.namespace, methods: []};
  file.methods.push(method);
  files.set(key, file);
}
async function writeProjections(program: Program, files: Map<string, ProjectionFile>, filename: string, className?: string): Promise<void> {
  for (const file of files.values()) {
    const methods = file.methods.join("\n");
    const body = className ? `internal static class ${className}\n{\n${methods}\n}` : methods;
    await emitFile(program, {path:recordOutput(program,resolve(program.projectRoot,"..",file.directory,filename)),content:`// <auto-generated/>\n#nullable enable\nusing System;\nusing System.Linq;\nusing System.Collections.Generic;\nnamespace ${file.namespace};\n${body}\n`});
  }
}
export function $storageProjection(ctx: DecoratorContext, source: Model, target: Model): void { ctx.program.stateMap(stateKeys.projection).set(source, target); }
export function $storageProjectionUsing(ctx: DecoratorContext, source: Type, method: string): void { ctx.program.stateMap(stateKeys.projectionUsing).set(source, method); }
export function $modelProjection(ctx: DecoratorContext, target: Model, source: Model, owner: Model | Namespace, projection?: Model): void {
  ctx.program.stateMap(stateKeys.modelProjection).set(target, {source, owner, computed: owner.kind === "Model" ? owner : undefined, projection});
}
export function $projectionSource(ctx: DecoratorContext, target: ModelProperty, source: ModelProperty): void { ctx.program.stateMap(stateKeys.projectionSource).set(target,source); }
export function $catalogProjection(ctx: DecoratorContext, target: Model, values: Union): void { ctx.program.stateMap(stateKeys.catalogProjection).set(target, values); }
export function $catalogValue(ctx: DecoratorContext, target: ModelProperty, symbol: string): void {
  if (!/^[A-Z][A-Za-z0-9]*$/u.test(symbol)) throw new Error(`Invalid catalog symbol ${symbol}`);
  ctx.program.stateMap(stateKeys.catalogValue).set(target, symbol);
}
export async function emitCatalogProjections(program: Program): Promise<void> {
  const files = new Map<string, ProjectionFile>();
  for (const [targetType, valueType] of program.stateMap(stateKeys.catalogProjection)) {
    const target = targetType as Model;
    const assignments = [...walkPropertiesInherited(target)].map((property,index) => {
      const symbol = program.stateMap(stateKeys.catalogValue).get(property);
      if (typeof symbol !== "string") throw new Error(`${target.name}.${property.name} requires a catalog symbol`);
      const type = mapType(program,property.type).replace(/\?$/u, "");
      const method = ({string:"AsString",long:"AsInt64",double:"AsDouble",bool:"AsBool"} as Record<string,string>)[type];
      if (!method) throw new Error(`Unsupported catalog projection type ${type}`);
      const name = property.name[0]!.toUpperCase()+property.name.slice(1);
      return `        ${name} = Nami.SemanticConventions.CollectorSemanticAttributeCatalog.${symbol} is { } key${index} ? attributes.GetValueOrDefault(key${index})?.${method}() : null,`;
    });
    appendProjection(program,files,target,`internal static class ${target.name}Factory\n{\n    internal static ${mapType(program,target)} FromAttributes(IReadOnlyDictionary<string, ${mapType(program,valueType as Union)}> attributes) => new()\n    {\n${assignments.join("\n")}\n    };\n}`);
  }
  await writeProjections(program,files,"AttributeCatalogProjection.g.cs");
}
export async function emitModelProjections(program: Program): Promise<void> {
  const files = new Map<string, ProjectionFile>();
  for (const [targetType, inputs] of program.stateMap(stateKeys.modelProjection)) {
    const target = targetType as Model;
    const {source, computed, projection, owner} = inputs as {source: Model; computed?: Model; projection?: Model; owner: Model | Namespace};
    const sourceProperties = new Map([...walkPropertiesInherited(source)].map(p => [p.name, p]));
    const computedProperties = new Map(computed ? [...walkPropertiesInherited(computed)].map(p => [p.name, p]) : []);
    const projectedProperties = new Map(projection ? [...walkPropertiesInherited(projection)].map(p => [p.name, p]) : []);
    const used = new Set<string>();
    const usedProjection = new Set<string>();
    const assignments = [...walkPropertiesInherited(target)].flatMap(property => {
      const column = program.stateMap(stateKeys.column).get(property) as {privateInit?: boolean} | undefined;
      if (column?.privateInit) return [];
      const computedInput = computedProperties.get(property.name);
      const projectedInput = projectedProperties.get(property.name);
      const mapped = program.stateMap(stateKeys.projectionSource).get(property) as ModelProperty | undefined;
      if (mapped && sourceProperties.get(mapped.name) !== mapped) throw new Error(`${target.name}.${property.name} maps a property outside ${source.name}`);
      if (computedInput && projectedInput) throw new Error(`${target.name}.${property.name} has two computed inputs`);
      const input = computedInput ?? projectedInput ?? mapped ?? sourceProperties.get(property.name);
      if (!input) throw new Error(`${source.name} -> ${target.name} has no input for ${property.name}; declare a computed value or a source property`);
      if (computedInput) used.add(property.name);
      if (projectedInput) usedProjection.add(property.name);
      const name = property.name[0]!.toUpperCase() + property.name.slice(1);
      const inputName = input.name[0]!.toUpperCase()+input.name.slice(1);
      return [`        ${name} = ${computedInput ? "computed" : projectedInput ? "projection" : "source"}.${inputName},`];
    });
    const unused = [...computedProperties.keys()].filter(key => !used.has(key));
    if (unused.length) throw new Error(`${computed!.name} has unused row inputs: ${unused.join(", ")}`);
    const unusedProjection = [...projectedProperties.keys()].filter(key => !usedProjection.has(key));
    if (unusedProjection.length) throw new Error(`${projection!.name} has unused row inputs: ${unusedProjection.join(", ")}`);
    appendProjection(program,files,owner,`    internal static ${mapType(program,target)} ToModel(${mapType(program,source)} source${computed ? `, ${mapType(program,computed)} computed` : ""}${projection ? `, ${mapType(program,projection)} projection` : ""}) => new()\n    {\n${assignments.join("\n")}\n    };`);
  }
  await writeProjections(program,files,"ModelMappings.g.cs","ModelMappings");
}
export async function emitProjections(program: Program): Promise<void> {
  const pairs = program.stateMap(stateKeys.projection) as Map<Model, Model>;
  if (pairs.size === 0) return;
  const external = program.stateMap(stateKeys.projectionUsing) as Map<Type,string>;
  const convert = (source: Type, target: Type, expression: string): string => {
    const method = external.get(source);
    if (method) return `${method}(${expression})`;
    if (source.kind === "Model" && target.kind === "Model") {
      if (isArrayModelType(source) && isArrayModelType(target)) {
        const item = convert(source.indexer!.value,target.indexer!.value,"item");
        return item === "item" ? expression : `${expression}.Select(item => ${item}).ToArray()`;
      }
      if (isRecordModelType(source) && isRecordModelType(target)) return `${expression}.ToDictionary(item => item.Key, item => ${convert(source.indexer!.value,target.indexer!.value,"item.Value")}, StringComparer.Ordinal)`;
      if (pairs.has(source)) return `ToStored(${expression})`;
    }
    return expression;
  };
  const files = new Map<string, ProjectionFile>();
  for (const [source,target] of pairs) {
    const derived = [...pairs].filter(([candidate])=> {
      let parent=candidate.baseModel; while(parent && parent!==source) parent=parent.baseModel;
      return parent===source;
    });
    let body: string;
    if (derived.length) body = `value switch\n    {\n${derived.map(([s])=>`        ${mapType(program,s)} item => ToStored(item),`).join("\n")}\n        null => throw new ArgumentNullException(nameof(value))\n    }`;
    else {
      const assignments = [...walkPropertiesInherited(target)].filter(p=>p.type.kind!=="String").map(property=> {
        const input = [...walkPropertiesInherited(source)].find(p=>p.name===property.name);
        if (!input) throw new Error(`Projection ${source.name} -> ${target.name} has no input for ${property.name}`);
        const name = property.name[0]!.toUpperCase()+property.name.slice(1);
        const expression=`value.${name}`;
        let conversion = convert(input.type,property.type,expression);
        if (input.optional && conversion !== expression) conversion = `${expression} is { } present${name} ? ${convert(input.type,property.type,`present${name}`)} : null`;
        return `        ${name} = ${conversion},`;
      });
      body=`new()\n    {\n${assignments.join("\n")}\n    }`;
    }
    appendProjection(program,files,target,`    internal static ${mapType(program,target)} ToStored(${mapType(program,source)} value) => ${body};`);
  }
  await writeProjections(program,files,"IngestionMappings.g.cs","IngestionMappings");
}
