import { recordOutput } from "./semantics.js";
import type { DecoratorContext, Program, Union } from "@typespec/compiler";
import { emitFile } from "@typespec/compiler";
import { resolve } from "node:path";
import { stateKeys } from "./lib.js";
import { mapType } from "./type-map.js";
import { outputFor } from "./outputs.js";

export function $slotValue(context: DecoratorContext, target: Union): void { context.program.stateMap(stateKeys.slot).set(target, true); }
export async function emitSlotValue(program: Program, union: Union): Promise<void> {
  const output = outputFor(program, union);
  if (!output) throw new Error(`Slot union ${union.name} requires a consumer output`);
  const name = union.name!;
  const variants = [...union.variants].map(([key, variant]) => {
    const type = variant.type;
    const empty = type.kind === "Intrinsic" && type.name === "null";
    const cs = type.kind === "Scalar" && type.name === "bytes" ? "byte[]" : mapType(program, type);
    const scalar = ["long", "double", "bool"].includes(cs);
    return {name:String(key),empty,cs,scalar,slot:`_${String(key).toLowerCase()}`};
  });
  const scalars = variants.filter(v=>v.scalar);
  const fields = scalars.map(v=>`    private readonly ${v.cs} ${v.slot};`).join("\n");
  const parameters = scalars.map(v=>`, ${v.cs} @${v.name.toLowerCase()} = default`).join("");
  const assignments = scalars.map(v=>`        ${v.slot} = @${v.name.toLowerCase()};`).join("\n");
  const methods = variants.map(v=>v.empty ? `    public static ${name} ${v.name} { get; } = new(${name}Kind.${v.name});` :
    `    public static ${name} From${v.name}(${v.cs} value) => new(${name}Kind.${v.name}, ${v.scalar ? `@${v.name.toLowerCase()}` : "reference"}: value);\n` +
    `    public ${v.cs}? As${v.cs === "long" ? "Int64" : v.name}() => Kind == ${name}Kind.${v.name} ? ${v.scalar ? v.slot : `(${v.cs})_reference!`} : null;`).join("\n");
  const content=`// <auto-generated/>\n#nullable enable\nusing System;\nusing System.Collections.Generic;\nnamespace ${output.namespace};\ninternal enum ${name}Kind { ${variants.map(v=>v.name).join(", ")} }\ninternal sealed partial class ${name}\n{\n${fields}\n    private readonly object? _reference;\n    private ${name}(${name}Kind kind${parameters}, object? reference = null)\n    {\n        Kind = kind;\n${assignments}\n        _reference = reference;\n    }\n    public ${name}Kind Kind { get; }\n${methods}\n}\n`;
  await emitFile(program, {path:recordOutput(program,resolve(program.projectRoot,"..",output.directory,`${name}.g.cs`)),content});
}
