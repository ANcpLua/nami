export function $tsBrand(context: DecoratorContext, target: Scalar): void {
  context.program.stateMap(stateKeys.tsBrand).set(target, true);
}

setTypeSpecNamespace("Nami.Api.Schema.Emit.TsTypes", $tsBrand);

const HEADER = "// <auto-generated/>\n// Copyright (c) 2025-2026 ancplua\n";

function isBuiltin(type: { namespace?: { name?: string; namespace?: { name?: string } } }): boolean {
  let cursor: { name?: string; namespace?: { name?: string } } | undefined = type.namespace;
  while (cursor) {
    if (cursor.name === "TypeSpec") return true;
    cursor = cursor.namespace;
  }
  return false;
}

export async function $onEmit(context: EmitContext): Promise<void> {
  const program = context.program;
  if (program.compilerOptions.noEmit) return;

  const brandBlock: string[] = [];
  const mediaTypeBlock: string[] = [];
  const modelBlock: string[] = [];
  const jsonModels: string[] = [];
  const jsonUnions: string[] = [];
  const serializable = new Map<string, Model | Union>();
  const enumBlock: string[] = [];
  const unionBlock: string[] = [];
  const emittedScalars = new Set<string>();
  const emittedMediaTypes = new Set<string>();
  const emittedModels = new Set<string>();
  const emittedEnums = new Set<string>();
  const emittedUnions = new Set<string>();
  /** JSON-schema definition name -> emitted TypeScript type, for the generated ContractDefinitions map. */
  const definitions = new Map<string, string>();

  navigateProgram(program, {
    scalar: (s) => {
      if (isBuiltin(s)) return;
      definitions.set(definitionName(s), program.stateMap(stateKeys.tsBrand).has(s) ? s.name : mapType(program, s));
      if (!program.stateMap(stateKeys.tsBrand).has(s)) return;
      if (emittedScalars.has(s.name)) return;
      emittedScalars.add(s.name);
      brandBlock.push(`export type ${s.name} = string & { readonly __brand: "${s.name}" };\n`);
      const pattern = getPattern(program, s);
      if (pattern !== undefined) {
        // The guard and the parser come from the scalar's own @pattern, so a cast is never needed.
        brandBlock.push(
          `const ${s.name}Pattern = new RegExp(${JSON.stringify(pattern)}, "u");\n` +
          `export function is${s.name}(value: string): value is ${s.name} {\n  return ${s.name}Pattern.test(value);\n}\n` +
          `export function parse${s.name}(value: string): ${s.name} {\n  if (!is${s.name}(value)) throw new TypeError(\`Not a ${s.name}: \${JSON.stringify(value)}\`);\n  return value;\n}\n`,
        );
      }
    },
    enum: (e) => {
      if (isBuiltin(e)) return;
      if (emittedEnums.has(e.name)) return;
      emittedEnums.add(e.name);
      enumBlock.push(renderEnum(e));
      definitions.set(definitionName(e), e.name);
    },
    model: (m) => {
      if (isBuiltin(m)) return;
      if (!m.name) return;
      collectMediaType(program, m, emittedMediaTypes, mediaTypeBlock);
      if (isArrayModelType(m)) return;
      if (isRecordModelType(m)) {
        if (m.name === "Record" || emittedModels.has(m.name)) return;
        emittedModels.add(m.name);
        modelBlock.push(renderRecordInterface(program, m));
        jsonModels.push(renderRecordInterface(program, m));
        serializable.set(m.name, m);
        return;
      }
      const isExplicitEmptyModel = m.properties.size === 0 && !m.baseModel;
      if (!hasBodyProperties(program, m) && !isExplicitEmptyModel) return;
      const name = emittedModelName(m);
      if (emittedModels.has(name)) return;
      emittedModels.add(name);
      modelBlock.push(renderInterface(program, m, name, false));
      jsonModels.push(renderInterface(program, m, name, true));
      serializable.set(name, m);
      definitions.set(getFriendlyName(program, m) ?? definitionName({ ...m, name }), name);
    },
    union: (u) => {
      if (isBuiltin(u) || !u.name || u.name.endsWith("Auth")) return;
      if (emittedUnions.has(u.name)) return;
      emittedUnions.add(u.name);
      unionBlock.push(renderUnion(program, u));
      jsonUnions.push(renderUnion(program, u));
      serializable.set(u.name, u);
      definitions.set(definitionName(u), u.name);
    },
  });

  const out = [HEADER, ...brandBlock, ...mediaTypeBlock, ...enumBlock, ...unionBlock, ...modelBlock];

  const path = `${context.emitterOutputDir}/api.ts`;
  await emitFile(program, { path, content: out.join("\n") });
  await emitFile(program, { path: `${context.emitterOutputDir}/json.ts`,
    content: [HEADER, ...brandBlock, ...mediaTypeBlock, ...enumBlock, ...jsonUnions, ...jsonModels].join("\n") });
  await emitFile(program, { path: `${context.emitterOutputDir}/serialization.ts`,
    content: renderSerialization(program, serializable, mapType) });

  await emitFile(program, { path: `${context.emitterOutputDir}/definitions.ts`, content: renderDefinitions(definitions) });
}

/** The JSON-schema definition name of a declared type: its namespace below the root, dotted, plus its name. */
function definitionName(type: { name?: string; namespace?: { name?: string; namespace?: unknown } }): string {
  const parts: string[] = [];
  let cursor = type.namespace;
  while (cursor && cursor.name) {
    parts.unshift(cursor.name);
    cursor = cursor.namespace as typeof cursor;
  }
  // The root is `Nami.Api.Contracts`; everything below it is the published spelling.
  const below = parts.slice(3);
  return [...below, type.name!].join(".");
}

function renderDefinitions(definitions: Map<string, string>): string {
  const entries = [...definitions.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const usedTypes = new Set<string>();
  for (const [, type] of entries) for (const name of type.match(/[A-Za-z_][A-Za-z0-9_]*/gu) ?? []) usedTypes.add(name);
  const keywords = new Set(["string", "number", "boolean", "bigint", "unknown", "null", "undefined", "never", "void", "any", "object"]);
  const knownTypes = new Set(entries.map(([, t]) => t).filter((t) => /^[A-Za-z_][A-Za-z0-9_]*$/u.test(t) && !keywords.has(t)));
  const imports = [...usedTypes].filter((name) => knownTypes.has(name)).sort();
  return (
    HEADER +
    `import type { ${imports.join(", ")} } from "./json.js";\n\n` +
    `/** Every OpenAPI component schema, by its component name, bound to the TypeScript type it describes. */\n` +
    `export interface ContractDefinitions {\n` +
    entries.map(([name, type]) => `  ${JSON.stringify(name)}: ${type};`).join("\n") +
    `\n}\n\nexport type ContractDefinitionName = keyof ContractDefinitions;\n`
  );
}

/**
 * A model that declares its own `@mediaTypeHint` (ProblemDetails) gets a constant for it; derived
 * models inherit the hint and do not repeat the constant. Mirrors the C# emitter.
 */
function collectMediaType(
  program: Program,
  model: Model,
  emitted: Set<string>,
  output: string[],
): void {
  const name = `${emittedModelName(model)}MediaType`;
  if (emitted.has(name)) return;
  const hint = getMediaTypeHint(program, model);
  if (hint === undefined) return;
  if (model.baseModel && getMediaTypeHint(program, model.baseModel) === hint) return;
  emitted.add(name);
  output.push(
    `export const ${name} = ${JSON.stringify(hint)} as const;\n` +
    `export type ${name} = typeof ${name};\n`,
  );
}

/**
 * Headers, parameters and the status code travel beside the body, and a `@body`/`@bodyRoot`
 * property *is* the body: a response envelope made only of these has no interface of its own.
 */
function isHttpMetadata(program: Program, property: ModelProperty): boolean {
  return isMetadata(program, property) || isBody(program, property) || isBodyRoot(program, property);
}

function renderEnum(e: Enum): string {
  const entries = [...e.members.values()]
    .map((m) => `  ${JSON.stringify(m.name)}: ${JSON.stringify(m.value ?? m.name)}`)
    .join(",\n");
  return `export const ${e.name}Values = {\n${entries},\n} as const;\nexport type ${e.name} = typeof ${e.name}Values[keyof typeof ${e.name}Values];\n`;
}

function renderUnion(program: Program, union: Union): string {
  const [discriminated] = getDiscriminatedUnion(program, union);
  const variants = [...union.variants.entries()].map(([name, variant]) => {
    const value = mapType(program, variant.type);
    return discriminated && variant.type.kind === "Model"
      ? `(${value} & { readonly ${JSON.stringify(discriminated.options.discriminatorPropertyName)}: ${JSON.stringify(String(name))} })`
      : value;
  });
  return `export type ${union.name} = ${[...new Set(variants)].join(" | ")};\n`;
}

function renderInterface(
  program: Program,
  m: Model,
  emittedName: string,
  wire: boolean,
): string {
  const base = m.baseModel ? ` extends ${emittedModelName(m.baseModel)}` : "";
  const lines: string[] = [`export interface ${emittedName}${base} {`];
  for (const [, prop] of m.properties) {
    if (isHttpMetadata(program, prop)) continue;
    const t = mapType(program, prop.type);
    const q = prop.optional ? "?" : "";
    const wireName = wire ? resolveEncodedName(program, prop, "application/json") : prop.name;
    lines.push(`  ${JSON.stringify(wireName)}${q}: ${t};`);
  }
  lines.push("}\n");
  return lines.join("\n");
}

function renderRecordInterface(
  program: Program,
  model: Model,
): string {
  const value = model.indexer?.value;
  if (!value) throw new Error(`Named record '${model.name}' has no indexer value.`);
  return `export interface ${model.name} {\n  [key: string]: ${mapType(program, value)};\n}\n`;
}

function hasBodyProperties(program: Program, model: Model): boolean {
  for (let current: Model | undefined = model; current; current = current.baseModel) {
    for (const property of current.properties.values()) {
      if (!isHttpMetadata(program, property)) return true;
    }
  }
  return false;
}

function emittedModelName(model: Model): string {
  if (!model.templateMapper?.args.length) return model.name;
  const parts = [model.name];
  for (const arg of model.templateMapper.args) {
    if ("kind" in arg && "name" in arg && typeof arg.name === "string") {
      parts.push(pascal(arg.name));
    }
  }
  return parts.join("");
}

function mapType(program: Program, type: Type): string {
  switch (type.kind) {
    case "Scalar": {
      const s = type as Scalar;
      if (program.stateMap(stateKeys.tsBrand).has(s)) return s.name;
      if (getEncode(program, s)?.type.name === "string") return "string";
      if (["int8","int16","int32","int64","uint8","uint16","uint32","uint64","float32","float64","decimal","decimal128"].includes(s.name)) return "number";
      if (s.name === "boolean") return "boolean";
      if (s.name === "bytes") return "string";
      if (s.name === "utcDateTime" || s.name === "offsetDateTime") return "string";
      if (s.name === "plainDate" || s.name === "plainTime") return "string";
      if (s.name === "duration") return "string";
      if (s.name === "url") return "string";
      if (s.name === "string") return "string";
      if (s.baseScalar) return mapType(program, s.baseScalar);
      reportDiagnostic(program, { code: "unmapped-type", target: s, format: { name: `scalar:${s.name}` } });
      return "unknown";
    }
    case "Model":
      if (isArrayModelType(type)) {
        // An anonymous union element needs parentheses: `string | number[]` is a union with an array.
        const element = mapType(program, type.indexer!.value);
        return element.includes(" | ") ? `(${element})[]` : `${element}[]`;
      }
      if (isRecordModelType(type)) {
        if (type.name && type.name !== "Record") return emittedModelName(type);
        return `Record<string, ${mapType(program, type.indexer!.value)}>`;
      }
      return emittedModelName(type);
    case "Enum":
      return (type as Enum).name;
    case "ModelProperty":
      // TypeSpec 1.13 constraint-based member access (e.g. `P.id`): the property
      // reference stands for the referenced property's type.
      return mapType(program, (type as { type: Type }).type);
    case "EnumMember": {
      const m = type as { value?: string | number; name: string };
      const v = m.value ?? m.name;
      return typeof v === "number" ? String(v) : `"${v}"`;
    }
    case "Union":
      if (type.name) return type.name;
      return [...type.variants.values()].map((variant) => mapType(program, variant.type)).join(" | ");
    case "UnionVariant":
      return mapType(program, (type as UnionVariant).type);
    case "Boolean":
      return String((type as BooleanLiteral).value);
    case "String":
      return JSON.stringify((type as StringLiteral).value);
    case "Number":
      return (type as NumericLiteral).valueAsString;
    case "Intrinsic": {
      const name = (type as IntrinsicType).name;
      if (name === "unknown" || name === "null" || name === "never" || name === "void") return name;
      reportDiagnostic(program, { code: "unmapped-type", target: type, format: { name: `intrinsic:${name}` } });
      return "unknown";
    }
    case "Tuple":
      return `[${(type as Tuple).values.map((value) => mapType(program, value)).join(", ")}]`;
    case "StringTemplate":
      return "string";
    default:
      reportDiagnostic(program, { code: "unmapped-type", target: type, format: { name: type.kind } });
      return "unknown";
  }
}

function pascal(value: string): string {
  return value.length === 0 ? value : value[0].toUpperCase() + value.slice(1);
}
