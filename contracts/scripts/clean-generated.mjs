import { readFile, rm } from "node:fs/promises";
import { csharpGeneratedDirectory, typescriptGeneratedDirectory, jsonSchemaDirectory, openApiPath, isGeneratedConsumerPath } from "./lib/paths.mjs";
await Promise.all([csharpGeneratedDirectory, typescriptGeneratedDirectory, jsonSchemaDirectory, openApiPath].map(path => rm(path, {force:true,recursive:true})));

const repository = new URL("../../", import.meta.url);
let files = [];
try { files = JSON.parse(await readFile(new URL("../generated/consumer-files.json",import.meta.url), "utf8")); }
catch(error) { if(error.code !== "ENOENT") throw error; }
for(const file of files) {
  if (!isGeneratedConsumerPath(file)) throw new Error(`Not an owned generated source: ${file}`);
  const path = new URL(file,repository);
  try {
    if (!(await readFile(path,"utf8")).startsWith("// <auto-generated/>")) throw new Error(`Generated marker missing: ${file}`);
    await rm(path,{force:true});
  } catch(error) { if(error.code !== "ENOENT") throw error; }
}
