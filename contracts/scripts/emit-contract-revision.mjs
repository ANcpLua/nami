import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { canonicalize } from "./lib/canonical-schema.mjs";
import { csharpRevisionPath, contractSchemasPath, typescriptGeneratedDirectory } from "./lib/paths.mjs";
const schemas = JSON.parse(await readFile(contractSchemasPath, "utf8"));
const wire = JSON.parse(await readFile(new URL("../generated/wire-manifest.json", import.meta.url), "utf8"));
for (const name of wire.roots) if (!(name in schemas)) throw new Error(`Missing wire root ${name}`);
const wireSchemas = Object.fromEntries(wire.roots.map(name => [name, schemas[name]]));
const revision = `sha256:${createHash("sha256").update(JSON.stringify(canonicalize(wireSchemas))).digest("hex")}`;
await mkdir(dirname(csharpRevisionPath),{recursive:true});
await writeFile(csharpRevisionPath, `// <auto-generated/>
#nullable enable
namespace Nami.Api.Contracts;
/// <summary>Fingerprint of the semantic wire schema, independent of presentation and package versions.</summary>
public static class ContractRevision
{
    public static readonly string Value = "${revision}";
}
`);
console.log(`emit-contract-revision: ${revision}`);

// Shared wire artifacts and configuration names: no second hand-maintained tool or key table.
await mkdir(typescriptGeneratedDirectory, {recursive: true});
const toolEntries = wire.tools.map(tool => ({...tool, description: schemas[tool.input].description ?? tool.input}));
const runtimeSchemas = new Set(["Common.ToolReadInput", "Common.ToolError", ...toolEntries.flatMap(tool => [tool.input, tool.output])]);
await writeFile(join(typescriptGeneratedDirectory, "contract-schemas.json"),
  JSON.stringify(Object.fromEntries([...runtimeSchemas].sort().map(name => [name, schemas[name]]))));
const version = (await readFile(new URL("../../Version.props", import.meta.url), "utf8"))
  .match(/<NamiVersion>([^<]+)<\/NamiVersion>/)?.[1];
if (!version) throw new Error("Version.props has no NamiVersion.");
const configuration = wire.configuration;
await writeFile(join(typescriptGeneratedDirectory, "manifest.ts"),
  `// <auto-generated/>\nexport const CONTRACT_REVISION = ${JSON.stringify(revision)};\n` +
  `export const PRODUCT_VERSION = ${JSON.stringify(version)};\n` +
  `export const TOOLS = ${JSON.stringify(toolEntries, null, 2)} as const;\n` +
  `export const CONFIG = ${JSON.stringify(configuration, null, 2)} as const;\n` +
  `export const CONFIG_DEFAULTS = ${JSON.stringify(wire.configurationDefaults, null, 2)} as const;\n` +
  `export const ENGINE_LIMITS = ${JSON.stringify(Object.fromEntries(Object.entries(schemas["Engine.EngineLimits"].properties).map(([name, value]) => [name, value.default])), null, 2)} as const;\n`);

await writeFile(join(typescriptGeneratedDirectory, "tool-contracts.ts"),
  `// <auto-generated/>
import type * as Json from "./json.js";
export interface ToolContracts {
` +
  toolEntries.map(t => `  ${JSON.stringify(t.name)}: { input: Json.${t.input.split(".").at(-1)}; result: Json.${t.output.split(".").at(-1)}; error: Json.${t.error.split(".").at(-1)} };`).join("\n") +
  `
}
export type ToolName = keyof ToolContracts;
export type ValidatedToolCall = { [N in ToolName]: { name: N; input: ToolContracts[N]["input"] } }[ToolName];
export type ToolReply<N extends ToolName> = { isError: false; result: ToolContracts[N]["result"] } | { isError: true; result: ToolContracts[N]["error"] };
export function validateToolCall(name: string, input: unknown, valid: (name: ToolName, input: unknown) => boolean): ValidatedToolCall | undefined {
` +
  toolEntries.map(t => `  if (name === ${JSON.stringify(t.name)} && valid(name, input)) return {name, input: input as ToolContracts[${JSON.stringify(t.name)}]["input"]};`).join("\n") +
  `
  return undefined;
}
`);
