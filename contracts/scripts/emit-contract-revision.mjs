import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { canonicalize } from "./lib/canonical-schema.mjs";
import { csharpRevisionPath, contractSchemasPath } from "./lib/paths.mjs";
const schemas = JSON.parse(await readFile(contractSchemasPath, "utf8"));
const revision = `sha256:${createHash("sha256").update(JSON.stringify(canonicalize(schemas))).digest("hex")}`;
await mkdir(dirname(csharpRevisionPath),{recursive:true});
await writeFile(csharpRevisionPath, `// <auto-generated/>
#nullable enable
namespace Nami.Api.Contracts;
/// <summary>Fingerprint of the semantic wire schema, independent of presentation and package versions.</summary>
public static class ContractRevision
{
    public static readonly string Value = "${revision}";
}
`);
console.log(`emit-contract-revision: ${revision}`);
