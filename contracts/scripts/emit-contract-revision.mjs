/**
 * Emits the contract revision into both generated faces of the contract.
 *
 * The revision hashes the semantic OpenAPI and normalized validation projections. Presentation-only
 * OpenAPI fields and `info.version` are removed and object keys are sorted
 * before hashing, so documentation edits and a release that changes nothing
 * but its version do not force a lockstep deploy, while any route, schema, or
 * operation change does. `info.version` never reaches the digest.
 *
 * It runs after the OpenAPI emit rather than inside an emitter because no
 * emitter can hash a file its own compile pass is still writing.
 *
 *   node scripts/emit-contract-revision.mjs            both faces
 *   node scripts/emit-contract-revision.mjs --csharp   C# only
 *   node scripts/emit-contract-revision.mjs --ts       TypeScript only
 */
import { createHash } from "node:crypto";
import { canonicalize } from "./lib/canonical-schema.mjs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { csharpRevisionPath as csharpPath, mcpApiPath as tsPath, mcpContractSchemasPath, openApiPath } from "./lib/paths.mjs";

// Everything from this line to the end of api.ts belongs to this script; the
// TypeSpec emitter owns everything above it. Re-running rewrites the block
// instead of stacking a second one.
const tsMarker = "// --- contract revision (scripts/emit-contract-revision.mjs) ---";

const flags = process.argv.slice(2);
const unknown = flags.filter((flag) => flag !== "--csharp" && flag !== "--ts");
if (unknown.length > 0) {
  throw new Error(`emit-contract-revision: unknown argument(s) ${unknown.join(", ")}`);
}
const emitCSharp = flags.length === 0 || flags.includes("--csharp");
const emitTs = flags.length === 0 || flags.includes("--ts");

// "Run `bun run compile`" is the right advice for a file that is not there yet and
// useless for one that is. An EACCES from a badly restored checkout, an EISDIR from a
// half-finished clean, an EMFILE under another process: told to compile, the operator
// compiles, watches it succeed, reruns the pack, and reads the identical message. So only
// ENOENT gets that sentence; everything else surfaces its own error as the cause.
async function readGenerated(path, what, missingAdvice) {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    const detail = error?.code === "ENOENT" ? `is missing — ${missingAdvice}` : `could not be read (${error?.code ?? error})`;
    throw new Error(`emit-contract-revision: ${what} '${path}' ${detail}.`, { cause: error });
  }
}

const openApi = JSON.parse(
  await readGenerated(
    openApiPath,
    "emitted OpenAPI document",
    "run `bun run compile` so the OpenAPI emit precedes the revision",
  ),
);

// Only `info.version` leaves: a version key anywhere else (a schema property
// named `version`, say) is contract.
const versionlessInfo = { ...openApi.info };
delete versionlessInfo.version;
const schemas = JSON.parse(await readGenerated(mcpContractSchemasPath, "normalized validation schemas", "run `bun run compile` so schema normalization precedes the revision"));
const revisionPayload = [
  "nami-contract-revision-v5",
  JSON.stringify(canonicalize({ ...openApi, info: versionlessInfo })),
  JSON.stringify(canonicalize(schemas)),
].join("\n");
const revision =
  `sha256:${createHash("sha256").update(revisionPayload).digest("hex").slice(0, 16)}`;

if (emitCSharp) {
  await mkdir(dirname(csharpPath), { recursive: true });
  await writeFile(
    csharpPath,
    `﻿// <auto-generated/>
// Copyright (c) 2025-2026 ancplua
#nullable enable

namespace Nami.Api.Contracts;

/// <summary>
/// The revision of the API contract these generated types were emitted from.
/// </summary>
public static class ContractRevision
{
    /// <summary>
    /// Matches <c>HealthReport.contract_revision</c> on a process serving this
    /// same contract. A client compares the two; while they differ, the two
    /// sides were built from different contracts.
    /// </summary>
    public static readonly string Value = "${revision}";
}
`,
  );
}

if (emitTs) {
  const api = await readGenerated(
    tsPath,
    "emitted TypeScript contract types",
    "run `bun run compile` so the TypeScript emit precedes the revision",
  );

  const markerIndex = api.indexOf(tsMarker);
  const emitted = markerIndex === -1 ? api : api.slice(0, markerIndex);
  await writeFile(
    tsPath,
    `${emitted.trimEnd()}\n\n${tsMarker}\n` +
      "/** Revision of the API contract these types were emitted from; compare against HealthReport.contract_revision. */\n" +
      `export const CONTRACT_REVISION: string = "${revision}";\n`,
  );
}

console.log(
  `emit-contract-revision: ${revision} -> ${
    [emitCSharp ? csharpPath : undefined, emitTs ? tsPath : undefined].filter(Boolean).join(", ")
  }`,
);
