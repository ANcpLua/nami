import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { canonicalize } from "./lib/canonical-schema.mjs";
import { csharpRevisionPath, contractSchemasPath, typescriptGeneratedDirectory } from "./lib/paths.mjs";
const schemas = JSON.parse(await readFile(contractSchemasPath, "utf8"));
const revision = `sha256:${createHash("sha256").update(JSON.stringify(canonicalize(schemas))).digest("hex")}`;
await mkdir(dirname(csharpRevisionPath),{recursive:true});
await writeFile(csharpRevisionPath, `// <auto-generated/>
#nullable enable
namespace Nami.Api.Contracts;
/// <summary>Fingerprint of the semantic wire schema, independent of presentation and package versions.</summary>
public static class ContractRevision
{
    public static readonly string Value = "${revision}";
}
`);
console.log(`emit-contract-revision: ${revision}`);

// Shared wire artifacts and configuration names: no second hand-maintained tool or key table.
await mkdir(typescriptGeneratedDirectory, {recursive: true});
const toolEntries = Object.entries(schemas).filter(([name]) => /^Tools\.\w+Input$/.test(name))
  .map(([input, schema]) => ({
    name: input.slice(6, -5).replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase(),
    description: schema.description ?? input,
    input, output: input.replace(/Input$/, "Result")
  })).sort((a, b) => a.name.localeCompare(b.name));
const runtimeSchemas = new Set(["Common.ToolReadInput", ...toolEntries.flatMap(tool => [tool.input, tool.output])]);
await writeFile(join(typescriptGeneratedDirectory, "contract-schemas.json"),
  JSON.stringify(Object.fromEntries([...runtimeSchemas].sort().map(name => [name, schemas[name]]))));
const configSource = await readFile(new URL("../../src/nami.collector.ingestion/Configuration/CollectorConfigurationKeys.cs", import.meta.url), "utf8");
const version = (await readFile(new URL("../../Version.props", import.meta.url), "utf8"))
  .match(/<NamiVersion>([^<]+)<\/NamiVersion>/)?.[1];
if (!version) throw new Error("Version.props has no NamiVersion.");
const configuration = Object.fromEntries([...configSource.matchAll(/public const string (\w+) = "([^"]+)";/g)]
  .map(([, name, value]) => [name, value]));
await writeFile(join(typescriptGeneratedDirectory, "manifest.ts"),
  `// <auto-generated/>\nexport const CONTRACT_REVISION = ${JSON.stringify(revision)};\n` +
  `export const PRODUCT_VERSION = ${JSON.stringify(version)};\n` +
  `export const TOOLS = ${JSON.stringify(toolEntries, null, 2)} as const;\n` +
  `export const CONFIG = ${JSON.stringify(configuration, null, 2)} as const;\n` +
  `export const ENGINE_LIMITS = ${JSON.stringify(Object.fromEntries(Object.entries(schemas["Engine.EngineLimits"].properties).map(([name, value]) => [name, value.default])), null, 2)} as const;\n`);
