            "ulong" or "System.UInt64" or "double" or "System.Double" or
            "System.DateTimeOffset" or "DateTimeOffset"
            ? $"{access} ?? throw new InvalidDataException(\"Arrow column '{column.ColumnName}' contains NULL.\")"
