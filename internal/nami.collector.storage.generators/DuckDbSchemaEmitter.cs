using ANcpLua.Roslyn.Utilities.Security;
using SourceString = ANcpLua.Roslyn.Utilities.StringExtensions;

namespace Nami.Collector.Storage.Generators;

internal static class DuckDbSchemaEmitter
{
    public static string Emit(IEnumerable<DuckDbTableInfo> discoveredTables)
    {
        var tables = discoveredTables
            .OrderBy(static table => table.TableName, StringComparer.Ordinal)
            .ToArray();
        var bootstrap = tables.Where(static table => table.Bootstrap).ToArray();
        var authoritative = tables.Where(static table => !table.Derived && !table.Bootstrap).ToArray();
        var derived = tables.Where(static table => table.Derived && !table.Bootstrap).ToArray();
        var sequences = SequenceDdl(authoritative);
        var derivedSequences = SequenceDdl(derived);

        var sb = new IndentedStringBuilder(32768);
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Canonical DuckDB schema identity and structural metadata.");
        sb.AppendLine();
        sb.AppendLine(GeneratedCodeHelpers.NullableEnable);
        sb.AppendLine();
        sb.AppendLine("namespace Nami.Collector.Storage;");
        sb.AppendLine();
        sb.AppendLine("internal readonly record struct DuckDbExpectedColumn(");
        sb.AppendLine("    string Name, string SqlType, bool Required, string? DefaultSql, int PrimaryKeyOrdinal);");
        sb.AppendLine("internal readonly record struct DuckDbExpectedIndex(");
        sb.AppendLine("    string Name, bool Unique, string[] Columns);");
        sb.AppendLine("internal sealed record DuckDbExpectedTable(");
        sb.AppendLine("    string Name, DuckDbExpectedColumn[] Columns, DuckDbExpectedIndex[] Indexes);");
        sb.AppendLine();
        sb.AppendLine("internal static class DuckDbGeneratedSchema");
        sb.BeginBlock();
        EmitDdlArray(sb, "BootstrapDdl", bootstrap, []);
        sb.AppendLine($"public const string AuthoritativeHash = \"{ComputeHash(bootstrap.Concat(authoritative).ToArray(), sequences)}\";");
        sb.AppendLine($"public const string DerivedHash = \"{ComputeHash(derived, derivedSequences)}\";");
        sb.AppendLine();
        EmitDdlArray(sb, "AuthoritativeDdl", authoritative, sequences);
        EmitDdlArray(sb, "DerivedDdl", derived, derivedSequences);
        EmitNameArray(sb, "BootstrapTableNames", bootstrap);
        EmitNameArray(sb, "AuthoritativeTableNames", authoritative);
        EmitNameArray(sb, "DerivedTableNames", derived);
        sb.AppendLine("public static readonly string[] DropAuthoritativeSequencesDdl =");
        sb.BeginBlock();
        foreach (var name in authoritative.SelectMany(static table => table.Columns).Select(static column => column.SequenceName)
                     .OfType<string>().Distinct(StringComparer.Ordinal).OrderBy(static name => name, StringComparer.Ordinal))
            sb.AppendLine($"\"{SourceString.EscapeCSharpString("DROP SEQUENCE IF EXISTS \"" + name.Replace("\"", "\"\"") + "\"")}\",");
        sb.EndBlock("};");
        EmitExpectedTables(sb, "BootstrapTables", bootstrap);
        EmitExpectedTables(sb, "AuthoritativeTables", authoritative);
        EmitExpectedTables(sb, "DerivedTables", derived);
        sb.EndBlock();
        return sb.ToString();
    }

    private static void EmitDdlArray(
        IndentedStringBuilder sb,
        string name,
        IReadOnlyList<DuckDbTableInfo> tables,
        IReadOnlyList<string> sequences)
    {
        sb.AppendLine($"public static readonly string[] {name} =");
        sb.BeginBlock();
        foreach (var sequence in sequences) sb.AppendLine($"\"{SourceString.EscapeCSharpString(sequence)}\",");
        foreach (var table in tables)
        {
            var qualifiedType = Qualify(table);
            sb.AppendLine($"{qualifiedType}.CreateTableDdl,");
            if (table.Indexes.Length > 0)
                sb.AppendLine($"{qualifiedType}.IndexesDdl,");
        }

        sb.EndBlock("};");
        sb.AppendLine();
    }

    private static void EmitNameArray(
        IndentedStringBuilder sb,
        string name,
        IReadOnlyList<DuckDbTableInfo> tables)
    {
        sb.AppendLine($"public static readonly string[] {name} =");
        sb.BeginBlock();
        foreach (var table in tables)
            sb.AppendLine($"\"{SourceString.EscapeCSharpString(table.TableName)}\",");
        sb.EndBlock("};");
        sb.AppendLine();
    }

    private static void EmitExpectedTables(
        IndentedStringBuilder sb,
        string name,
        IReadOnlyList<DuckDbTableInfo> tables)
    {
        sb.AppendLine($"public static readonly DuckDbExpectedTable[] {name} =");
        sb.BeginBlock();
        foreach (var table in tables)
        {
            sb.AppendLine($"new(\"{SourceString.EscapeCSharpString(table.TableName)}\",");
            sb.AppendLine("new DuckDbExpectedColumn[]");
            sb.BeginBlock();
            foreach (var column in table.Columns)
            {
                sb.AppendLine(
                    $"new(\"{SourceString.EscapeCSharpString(column.ColumnName)}\", \"{SourceString.EscapeCSharpString(DuckDbEmitter.ResolveSqlType(column))}\", " +
                    $"{Bool(!column.IsNullable)}, {NullableString(column.DefaultSql)}, {column.PrimaryKeyOrdinal}),");
            }

            sb.EndBlock("},");
            sb.AppendLine("new DuckDbExpectedIndex[]");
            sb.BeginBlock();
            foreach (var index in table.Indexes)
            {
                var columns = string.Join(", ", index.ColumnNames.Select(static column => $"\"{SourceString.EscapeCSharpString(column)}\""));
                sb.AppendLine(
                    $"new(\"{SourceString.EscapeCSharpString(index.Name)}\", {Bool(index.IsUnique)}, [{columns}]),");
            }

            sb.EndBlock("}),");
        }

        sb.EndBlock("};");
        sb.AppendLine();
    }

    private static string[] SequenceDdl(IReadOnlyList<DuckDbTableInfo> tables) => tables
        .SelectMany(static table => table.Columns).Select(static column => column.SequenceName)
        .OfType<string>().Distinct(StringComparer.Ordinal).OrderBy(static name => name, StringComparer.Ordinal)
        .Select(static name => "CREATE SEQUENCE IF NOT EXISTS \"" + name.Replace("\"", "\"\"") + "\" START 1")
        .ToArray();

    private static string ComputeHash(IReadOnlyList<DuckDbTableInfo> tables, IReadOnlyList<string> sequences) =>
        Sha256Hex.Hash("nami-duckdb-generated-ddl/v2\n" + string.Concat(sequences.Select(static ddl => ddl + "\n")) +
                  string.Concat(tables.OrderBy(static table => table.TableName, StringComparer.Ordinal).Select(CanonicalTable)));

    private static string CanonicalTable(DuckDbTableInfo table)
    {
        var canonical = new StringBuilder();
        canonical.AppendLine(DuckDbEmitter.BuildCreateTableDdl(table));
        var indexes = DuckDbEmitter.BuildIndexesDdl(table);
        if (indexes.Length > 0)
            canonical.AppendLine(indexes);
        return canonical.ToString();
    }

    private static string Qualify(DuckDbTableInfo table) =>
        string.IsNullOrEmpty(table.Namespace) || table.Namespace == "<global namespace>"
            ? $"global::{table.TypeName}"
            : $"global::{table.Namespace}.{table.TypeName}";

    private static string NullableString(string? value) =>
        value is null ? "null" : $"\"{SourceString.EscapeCSharpString(value)}\"";

    private static string Bool(bool value) => value ? "true" : "false";

}
