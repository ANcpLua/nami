using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Nami.IntegrationTests.InterceptorProbe;

/// <summary>Redirects every call of a static, parameterless <c>Probe.Target()</c> to a generated wrapper.</summary>
[Generator]
public sealed class InterceptorProbeGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var calls = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is InvocationExpressionSyntax
                {
                    Expression: MemberAccessExpressionSyntax { Name.Identifier.ValueText: "Target" }
                },
                static (syntax, cancellationToken) => Locate(syntax, cancellationToken))
            .Where(static call => call.Data.Length != 0)
            .Collect();
        context.RegisterSourceOutput(calls, static (production, located) => Emit(production, located));
    }

    private static (int Version, string Data, string Display, string Callee) Locate(GeneratorSyntaxContext context,
        CancellationToken cancellationToken)
    {
        var invocation = (InvocationExpressionSyntax)context.Node;
        if (context.SemanticModel.GetSymbolInfo(invocation, cancellationToken).Symbol is not IMethodSymbol
            {
                IsStatic: true, Parameters.Length: 0, ReturnType.SpecialType: SpecialType.System_String,
                ContainingType.Name: "Probe"
            } target)
            return (0, "", "", "");
        var location = context.SemanticModel.GetInterceptableLocation(invocation, cancellationToken);
        return location is null
            ? (0, "", "", "")
            : (location.Version, location.Data, location.GetDisplayLocation(),
                target.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
    }

    private static void Emit(SourceProductionContext production,
        ImmutableArray<(int Version, string Data, string Display, string Callee)> located)
    {
        if (located.IsEmpty) return;
        var source = new StringBuilder("""
                                       // <auto-generated/>
                                       #nullable enable
                                       namespace System.Runtime.CompilerServices
                                       {
                                           [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]
                                           file sealed class InterceptsLocationAttribute : global::System.Attribute
                                           {
                                               public InterceptsLocationAttribute(int version, string data)
                                               {
                                                   _ = version;
                                                   _ = data;
                                               }
                                           }
                                       }

                                       namespace Nami.IntegrationTests.InterceptorProbe.Generated
                                       {
                                           internal static class ProbeInterceptors
                                           {

                                       """);
        var index = 0;
        foreach (var call in located.OrderBy(static call => call.Data, StringComparer.Ordinal))
        {
            source.Append("        // ").AppendLine(call.Display);
            source.Append("        [global::System.Runtime.CompilerServices.InterceptsLocation(")
                .Append(call.Version.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(SymbolDisplay.FormatLiteral(call.Data, true)).AppendLine(")]");
            source.Append("        internal static string Target").Append(index.ToString(CultureInfo.InvariantCulture))
                .Append("() => ").Append(call.Callee).AppendLine(".Target();");
            index++;
        }

        source.AppendLine("    }").AppendLine("}");
        production.AddSource("ProbeInterceptors.g.cs", source.ToString());
    }
}
